"""A manuscript may not credit a module that does not exist.

WHY. The papers credit their generators in table captions - "Generated by
\\texttt{src/pkinv/...}" - and those credits are how a reader finds the code behind a
published table. Nothing checked them, and by the agriculture pass FOUR were wrong at once:
two named `src/pkinv/inventory/...` paths that predate the sectors/ layout, one named
`src/pkinv/eval/district_crosscheck.py` and one `src/pkinv/eval/buffalo_implied_ef.py` -
both removed in rc36, which audited code references, documentation and `\\includegraphics`
but not the manuscripts' own prose. A credit is a citation, and a citation to a file that is
not there is worse than no citation: it tells a reader the derivation is reproducible when
it is not.

The generated completeness table had the identical defect (it cited a module that had moved
sectors) and rc36 fixed that ONE instance. This is the class.

WHAT COUNTS. Every `\\texttt{...}` in the manuscripts whose content looks like a repository
path into src/, scripts/ or tests/. Shell globs are honoured as globs - the waste appendix
credits `scripts/make_waste_*_table.py`, which is three real scripts and an honest way to
name them - and a glob matching nothing fails like any other missing credit.

Run:  python3 -m unittest discover tests -p "test_manuscript_module_credits.py"
"""

from pkinv.assets import asset_path
import glob
import os
from pkinv.paths import PAPER_NATIONAL_MAIN  # noqa: E402
import re
import unittest

from pkinv.report.artifact_inventory import as_a_reader_sees_it

from _support import ROOT

TEX = sorted(glob.glob(os.path.join(ROOT, "papers", "**", "*.tex"), recursive=True)
             + glob.glob(os.path.join(PAPER_NATIONAL_MAIN, "**", "*.tex"), recursive=True)
             + glob.glob(os.path.join(ROOT, "paper_common", "*.tex")))
CREDIT = re.compile(r"\\texttt\{((?:src|scripts|tests)/[^}]+)\}")


def _credits():
    """[(path as printed, tex file)] over every manuscript."""
    out = []
    for tex in TEX:
        with open(tex, encoding="utf-8") as f:
            text = f.read()
        for m in CREDIT.finditer(text):
            # the shared normaliser, not a local copy: a credited path that needed a break
            # hint would otherwise be reported as a module that does not exist (cycle 36)
            printed = as_a_reader_sees_it(m.group(1))
            out.append((printed, os.path.relpath(tex, ROOT)))
    return out


class TestEveryCreditedModuleExists(unittest.TestCase):

    def test_the_sweep_is_looking_at_something(self):
        """A regex that matched nothing would pass this file forever."""
        credits = _credits()
        # 18 credits across 12 sections when this guard was written; the floors sit just
        # under, so a pattern that silently stops matching fails instead of passing empty.
        self.assertGreaterEqual(len(credits), 15,
                                "the manuscripts credit %d modules; the pattern has "
                                "stopped matching" % len(credits))
        self.assertGreaterEqual(len({tex for _p, tex in credits}), 10)

    def test_every_credited_path_is_on_disk(self):
        missing = []
        for printed, tex in _credits():
            full = asset_path(ROOT, printed)
            if any(ch in printed for ch in "*?["):
                if not glob.glob(full):
                    missing.append("%s -> %s (glob matches nothing)" % (tex, printed))
            elif not os.path.exists(full):
                missing.append("%s -> %s" % (tex, printed))
        self.assertFalse(
            missing,
            "a manuscript credits a module that is not here. Either the module moved (fix "
            "the credit), or it was removed while a paper still cites it as the generator "
            "of a published table (restore it, or rewrite the caption to describe the "
            "derivation without crediting code that does not exist):\n  "
            + "\n  ".join(sorted(missing)))

    def test_a_planted_credit_would_be_caught(self):
        """The detector, tested against a name chosen to appear nowhere."""
        planted = "src/pkinv/zz_no_such_module_credits_selftest.py"
        self.assertFalse(os.path.exists(asset_path(ROOT, planted)))
        self.assertFalse(glob.glob(asset_path(ROOT, planted)))

    cfg = rows_of(asset_path(root, "outputs", "national_configurations.csv"))
    fam = defaultdict(list)
    for r in cfg:
        if r.get("family_id"):
            fam[r["family_id"]].append(r["configuration_id"])
    rows = []
    for f, members in sorted(fam.items()):
        for i, a in enumerate(members):
            for b in members[i + 1:]:
                rows.append({"configuration_a": a, "configuration_b": b, "family_id": f,
                             "rule": "members of one family are alternatives for the same quantity and cannot be combined"})
    return write(out, ["configuration_a", "configuration_b", "family_id", "rule"], rows,
                 extra_note="THE ONLY COMBINATION RULE THE RELEASE ENCODES: configurations sharing a family_id "
                            "in outputs/national_configurations.csv are mutually exclusive. No other "
                            "invalid-combination register exists; combinations across families were not "
                            "evaluated and carry no claim either way (see KNOWN_EXCEPTIONS.json).")



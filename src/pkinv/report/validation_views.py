def test_catalogue(root, out, themes):
    import re
    rows = []
    for folder, dirs, names in os.walk(asset_path(root, "tests")):
        dirs[:] = [d for d in dirs if d != "__pycache__"]
        for name in sorted(names):
            if not (name.startswith("test_") and name.endswith(".py")):
                continue
            rel = os.path.relpath(asset_path(folder, name), root)
            with open(asset_path(folder, name), encoding="utf-8") as handle:
                text = handle.read()
            n = len(re.findall(r"^\s+def (test_\w+)", text, re.M))
            theme = "other"
            for t, pattern in themes:
                if re.search(pattern, rel):
                    theme = t
                    break
            doc = (re.match(r'\s*"""(.*?)(?:\n|""")', text, re.S) or re.match(r"\s*'''(.*?)(?:\n|''')", text, re.S))
            rows.append({"test_file": rel, "theme": theme, "tests": n,
                         "first_line": (doc.group(1).strip() if doc else "")[:160]})
    return write(out, ["test_file", "theme", "tests", "first_line"], rows,
                 extra_note="every test module with a theme from the reviewer's grouping; modules stay flat "
                            "because unittest discover and tests/_support.py resolve them from tests/")

def _monthly(root):
    return rows_of(asset_path(root, "outputs", "pakemis_monthly_fy2015_16_fy2023_24.csv"))


def annual_monthly_closure(root, out):
    atoms = {(r["period_id"], r["component_id"], r["configuration_id"], r["geography_id"]): r
             for r in _atomic(root)}
    months = defaultdict(lambda: {"n": 0, "sum": 0.0, "share": 0.0})
    for r in _monthly(root):
        k = (r["period_id"], r["component_id"], r["configuration_id"], r["geography_id"])
        months[k]["n"] += 1
        months[k]["sum"] += float(r["co2e_Mt_AR5"] or 0)
        months[k]["share"] += float(r["share"] or 0)
    rows = []
    for k, d in sorted(months.items()):
        a = atoms.get(k)
        annual = float(a["co2e_Mt_AR5"]) if a and a["co2e_Mt_AR5"] else None
        rows.append({"period_id": k[0], "component_id": k[1], "configuration_id": k[2], "geography_id": k[3],
                     "months": d["n"], "sum_of_shares": fmt(d["share"]),
                     "annual_Mt_AR5": fmt(annual) if annual is not None else "",
                     "sum_of_months_Mt_AR5": fmt(d["sum"]),
                     "residual_Mt": fmt(d["sum"] - annual) if annual is not None else "",
                     # relative 1e-9 with an absolute floor of 1e-8 Mt: the monthly values are
                     # PRINTED at 9 decimals, so twelve of them can differ from the annual by
                     # up to 6e-9 Mt of rounding; the in-process identity is asserted at
                     # 1e-9 relative by tests/test_monthly_all_years.py on unrounded values
                     "closes_1e-9_rel": ("yes" if annual is not None and
                                         abs(d["sum"] - annual) <= max(1e-9 * abs(annual), 1e-8) and d["n"] == 12
                                         else "no")})
    return write(out, ["period_id", "component_id", "configuration_id", "geography_id", "months",
                       "sum_of_shares", "annual_Mt_AR5", "sum_of_months_Mt_AR5", "residual_Mt", "closes_1e-9_rel"],
                 rows, extra_note="per atom: twelve monthly rows summed against the atomic annual value")


def monthly_exceptions(root, out):
    acc = OrderedDict()
    for r in _monthly(root):
        flags = []
        if r.get("borrowed_from_year"):
            flags.append("profile borrowed from %s" % r["borrowed_from_year"])
        if r.get("special_period_flag"):
            flags.append("special period: %s" % r["special_period_flag"])
        if r.get("temporal_evidence_class") == "TE4":
            flags.append("TE4 (no month-resolving evidence; flat or stock-driven)")
        if not flags:
            continue
        k = (r["period_id"], r["component_id"], r["configuration_id"], "; ".join(flags))
        d = acc.setdefault(k, {"months": 0, "Mt": 0.0})
        d["months"] += 1
        d["Mt"] += float(r["co2e_Mt_AR5"] or 0)
    rows = [{"period_id": k[0], "component_id": k[1], "configuration_id": k[2], "exception": k[3],
             "months_affected": d["months"], "co2e_Mt_AR5": fmt(d["Mt"])} for k, d in acc.items()]
    return write(out, ["period_id", "component_id", "configuration_id", "exception", "months_affected", "co2e_Mt_AR5"],
                 rows, extra_note="the monthly panel's own flags (borrowed_from_year, special_period_flag, "
                                  "TE4) aggregated per atom; the release keeps no separate monthly "
                                  "exception ledger - the physical timing decomposition is "
                                  "outputs/pakemis_temporal_decomposition.csv")



def ar5_ar6_bridge(root, out):
    keys = ["period_id", "configuration_id", "geography_id", "gas"]
    rows = _grouped(_atomic(root), keys)
    for r in rows:
        a5, a6 = float(r["co2e_Mt_AR5"]), float(r["co2e_Mt_AR6"])
        r["AR6_minus_AR5_Mt"] = fmt(a6 - a5)
        r["ratio_AR6_over_AR5"] = fmt(a6 / a5) if a5 else ""
    return write(out, keys + ["co2e_Mt_AR5", "co2e_Mt_AR6", "AR6_minus_AR5_Mt", "ratio_AR6_over_AR5"], rows,
                 extra_note="the two CO2e columns of the atomic table grouped by gas; GWP values "
                            "are registries/gwp.csv")


def annual_closure_report(root, out):
    """Per period and configuration: the atomic sum against the annual panel and the national series."""
    atoms = _atomic(root)
    panel = rows_of(asset_path(root, "outputs", "pakemis_annual_fy2015_16_fy2023_24.csv"))
    series = rows_of(asset_path(root, "outputs", "pakemis_national_series.csv"))
    atomic = defaultdict(float)
    for r in atoms:
        if r["estimate_status"] == "E":
            atomic[(r["period_id"], r["configuration_id"])] += float(r["co2e_Mt_AR5"] or 0)
    panel_sum = defaultdict(float)
    for r in panel:
        if r.get("grain", "") == "category_gas" and r["co2e_Mt_AR5"]:
            panel_sum[(r["period_label"], r["configuration_id"])] += float(r["co2e_Mt_AR5"])
    series_total = {}
    for r in series:
        if r["row_kind"] == "covered_total":
            series_total[r["period_label"]] = float(r["co2e_Mt_AR5"] or 0)
    rows = []
    for (period, cfg), value in sorted(atomic.items()):
        p = panel_sum.get((period, cfg))
        s = series_total.get(period) if cfg == "REF_2023_24" else None
        rows.append({"period_id": period, "configuration_id": cfg, "atomic_sum_Mt_AR5": fmt(value),
                     "annual_panel_sum_Mt_AR5": fmt(p) if p is not None else "",
                     "panel_minus_atomic_Mt": fmt(p - value) if p is not None else "",
                     "national_series_total_Mt_AR5": fmt(s) if s is not None else "",
                     "series_minus_atomic_Mt": fmt(s - value) if s is not None else ""})
    return write(out, ["period_id", "configuration_id", "atomic_sum_Mt_AR5", "annual_panel_sum_Mt_AR5",
                       "panel_minus_atomic_Mt", "national_series_total_Mt_AR5", "series_minus_atomic_Mt"], rows,
                 extra_note="sums of three shipped products that describe the same years; the tests "
                            "that assert the identities are tests/test_atomic_annual.py, "
                            "test_annual_product.py, test_national_series.py")



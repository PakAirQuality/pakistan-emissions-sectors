def correlation_matrix(root, out):
    """The block matrix the dependency groups imply: 1 within a group, 0 across."""
    params = rows_of(asset_path(root, "outputs", "national_uncertainty_parameters.csv"))
    drawable = [p for p in params if p.get("distribution") not in ("", "structural", "none")]
    groups = defaultdict(list)
    for p in drawable:
        groups[p["dependency_group"] or p["parameter_id"]].append(p["parameter_id"])
    rows = []
    for g, members in sorted(groups.items()):
        if len(members) < 2:
            continue
        for i, a in enumerate(members):
            for b in members[i + 1:]:
                rows.append({"parameter_a": a, "parameter_b": b, "dependency_group": g, "implied_correlation": "1",
                             "basis": "same dependency group: one shared z draw"})
    return write(out, ["parameter_a", "parameter_b", "dependency_group", "implied_correlation", "basis"], rows,
                 extra_note="NOT AN ESTIMATED MATRIX. The Monte Carlo's correlation model is structural: "
                            "parameters in one dependency group share one standard-normal draw (implied "
                            "correlation 1, or -1 where parameter_scope.csv gives the member a negative sign) "
                            "and every other pair is independent (0). Only the non-trivial pairs are listed; "
                            "every pair not listed has implied correlation 0. The rules are "
                            "data/dependency_group_rules.csv, the scopes data/parameter_scope.csv.")



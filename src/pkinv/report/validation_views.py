def _parse_key(text):
    return dict(part.split("=", 1) for part in text.split(";"))


def cross_sector_registry(root, out):
    mapping = rows_of(asset_path(root, "data", "cross_sector_ledger_map.csv"))
    rows = []
    for m in mapping:
        src = rows_of(asset_path(root, m["source_file"]))
        key = _parse_key(m["row_key"])
        hits = [r for r in src if all(r.get(c) == v for c, v in key.items())]
        if len(hits) != 1:
            raise ValueError("ledger map %s/%s resolves to %d rows" % (m["ledger_id"], m["row_id"], len(hits)))
        value = hits[0][m["value_column"]]
        rows.append({
            "ledger_id": m["ledger_id"], "row_id": m["row_id"], "kind": m["kind"], "period_id": m["period_id"],
            "configuration_id": m["configuration_id"], "origin_sector": m["origin_sector"],
            "origin_source_stream": m["origin_source_stream"], "destination_sector": m["destination_sector"],
            "destination_source_stream": m["destination_source_stream"], "activity_mass_or_energy": value,
            "units": m["units"], "origin_emissions_effect": m["origin_emissions_effect"],
            "destination_emissions_effect": m["destination_emissions_effect"],
            "unresolved_amount": value if m["kind"] == "unresolved" else "",
            "closure_residual": "", "source_ids": m["source_ids"], "method_id": m["method_id"],
            "status": m["status"], "source_file": m["source_file"], "row_key": m["row_key"],
            "value_column": m["value_column"]})
    return write(out, ["ledger_id", "row_id", "kind", "period_id", "configuration_id", "origin_sector",
                       "origin_source_stream", "destination_sector", "destination_source_stream",
                       "activity_mass_or_energy", "units", "origin_emissions_effect", "destination_emissions_effect",
                       "unresolved_amount", "closure_residual", "source_ids", "method_id", "status",
                       "source_file", "row_key", "value_column"], rows,
                 extra_note="one row per pointer in data/cross_sector_ledger_map.csv, with the value read "
                            "from the sector ledger it names (source_file, row_key, value_column)")


def cross_sector_closure_report(root, out):
    reg = cross_sector_registry(root, asset_path(os.path.dirname(out), "_tmp_registry.csv"))
    os.remove(asset_path(os.path.dirname(out), "_tmp_registry.csv"))
    sums = OrderedDict()
    for r in reg:
        x = float(r["activity_mass_or_energy"]) if r["activity_mass_or_energy"] not in ("", None) else 0.0
        for cfg in r["configuration_id"].split(";"):
            d = sums.setdefault((r["ledger_id"], cfg), {"control": 0.0, "transfer": 0.0, "unresolved": 0.0,
                                                          "memo": 0.0, "units": r["units"], "n": 0})
            d[r["kind"]] += x
            d["n"] += 1
    rows = []
    for (ledger, cfg), d in sums.items():
        residual = d["control"] - d["transfer"] - d["unresolved"]
        rows.append({"ledger_id": ledger, "configuration_id": cfg, "rows": d["n"], "control": fmt(d["control"]),
                     "sum_transfers": fmt(d["transfer"]), "sum_unresolved": fmt(d["unresolved"]),
                     "closure_residual": fmt(residual), "units": d["units"].split(" ")[0] if d["units"] else "",
                     "status": "closes" if abs(residual) <= 2e-4 * max(1.0, abs(d["control"]) / 100.0) or abs(residual) <= 2e-4
                     else "OPEN"})
    return write(out, ["ledger_id", "configuration_id", "rows", "control", "sum_transfers", "sum_unresolved",
                       "closure_residual", "units", "status"], rows,
                 extra_note="per ledger and configuration: control - transfers - unresolved, from the registry "
                            "view; residuals at the ledgers' printed precision (4 dp) are rounding")



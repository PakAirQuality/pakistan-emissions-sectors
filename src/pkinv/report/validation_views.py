def grid_closure(root, out):
    """Per month and gas: the cube's cell sum against the national monthly product."""
    try:
        import numpy as np
        from netCDF4 import Dataset
    except ImportError:
        return write(out, ["month", "gas", "note"], [{"month": "", "gas": "", "note":
                     "netCDF4/numpy not importable when the package was built; see "
                     "tests/test_grid_cube.py for the asserted identity"}])
    monthly = defaultdict(float)
    for r in _monthly(root):
        if r["period_id"] == "FY2023-24" and r["configuration_id"] == "REF_2023_24":
            monthly[(r["month"], r["gas"].upper())] += float(r["emission_native_mass"] or 0)
    unalloc = defaultdict(float)
    for r in rows_of(asset_path(root, "outputs", "pakemis_spatial_unallocated.csv")):
        unalloc[(r["month"], r["gas"].upper())] += float(r["emissions_Gg"] or 0)
    rows = []
    with Dataset(asset_path(root, "outputs", "pakemis_grid_0p05_monthly.nc")) as ds:
        months = sorted({m for m, _ in monthly})
        for var, gas in (("co2_Gg", "CO2"), ("ch4_Gg", "CH4"), ("n2o_Gg", "N2O")):
            # KEEP THE MASK (rc45). netCDF4 auto-masks on read and the writer stores
            # _FillValue = -9999 in every out-of-country cell, so np.asarray(...) drops the
            # mask and hands the fill values straight to the sum. This view shipped in the
            # rc44 package reporting a grid sum of -570,989,101 Gg against a true 13,793 -
            # exactly -9999 x 57,106 outside cells, identical in every month and gas row.
            # The closure view is the first thing a reviewer opens, and it was reporting the
            # count of the sea. np.ma.sum honours the mask; the correct pattern was already
            # in tests/test_grid_cube.py:608, which keeps the masked array and calls .sum().
            arr = ds.variables[var][:]
            for i, month in enumerate(months[:arr.shape[0]]):
                cells = float(np.ma.sum(arr[i]))
                nat = monthly.get((month, gas), 0.0)
                un = unalloc.get((month, gas), 0.0)
                rows.append({"month": month, "gas": gas, "grid_sum_Gg": fmt(cells), "grid_unallocated_Gg": fmt(un),
                             "national_monthly_Gg": fmt(nat), "residual_Gg": fmt(cells + un - nat)})
    return write(out, ["month", "gas", "grid_sum_Gg", "grid_unallocated_Gg", "national_monthly_Gg", "residual_Gg"],
                 rows, extra_note="sum over cells of outputs/pakemis_grid_0p05_monthly.nc plus the retained "
                                  "(unallocated) mass of outputs/pakemis_spatial_unallocated.csv against the "
                                  "reference-year monthly panel, per gas in native Gg; the gas vocabulary and "
                                  "month coverage of the three files are compared as shipped")



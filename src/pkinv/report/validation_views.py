def sectors_registry(root, out):
    with open(asset_path(root, "outputs", "release_manifest.json"), encoding="utf-8") as handle:
        manifest = json.load(handle)
    atoms = _atomic(root)
    per = defaultdict(lambda: {"atoms": 0, "Mt": 0.0, "codes": set()})
    for r in atoms:
        if r["period_id"] == "FY2023-24" and r["configuration_id"] == "REF_2023_24":
            d = per[r["sector_id"]]
            d["atoms"] += 1
            d["Mt"] += float(r["co2e_Mt_AR5"] or 0)
            d["codes"].add(r["ipcc_code"])
    rows = []
    for s in manifest["sectors"]:
        # rc41 (D-1): the manifest keys each sector row on "sector", not "id" - the old
        # lookup fell through to str(s) and wrote the dict's repr as the sector id, so the
        # view carried ten stringified dicts with zero atoms
        sid = s if isinstance(s, str) else s.get("sector") or s.get("id") or str(s)
        d = per.get(sid, {"atoms": 0, "Mt": 0.0, "codes": set()})
        rows.append({"sector_id": sid, "runner": "pkinv.sectors.%s" % sid, "atoms_reference_year": d["atoms"],
                     "co2e_Mt_AR5_reference_year": fmt(d["Mt"]), "ipcc_codes": ";".join(sorted(d["codes"]))})
    return write(out, ["sector_id", "runner", "atoms_reference_year", "co2e_Mt_AR5_reference_year", "ipcc_codes"], rows,
                 extra_note="the sector list of outputs/release_manifest.json, joined to the atomic table; "
                            "sector_id is DERIVED in src/pkinv/core/components.py, never typed")


def components_registry(root, out):
    atoms = _atomic(root)
    seen = OrderedDict()
    for r in atoms:
        k = r["component_id"]
        d = seen.setdefault(k, {"sector_id": r["sector_id"], "ipcc_code": r["ipcc_code"], "category": r["category"],
                                "subitem": r["subitem"], "gas": r["gas"], "gas_origin": r["gas_origin"],
                                "source_stream_id": r["source_stream_id"], "method_id": r["method_id"],
                                "uncertainty_model_id": r["uncertainty_model_id"], "periods": set(), "configurations": set()})
        d["periods"].add(r["period_id"])
        d["configurations"].add(r["configuration_id"])
    rows = []
    for k, d in seen.items():
        row = {"component_id": k}
        row.update({c: d[c] for c in ("sector_id", "ipcc_code", "category", "subitem", "gas", "gas_origin",
                                       "source_stream_id", "method_id", "uncertainty_model_id")})
        row["periods"] = len(d["periods"])
        row["configurations"] = ";".join(sorted(d["configurations"]))
        rows.append(row)
    return write(out, ["component_id", "sector_id", "ipcc_code", "category", "subitem", "gas", "gas_origin",
                       "source_stream_id", "method_id", "uncertainty_model_id", "periods", "configurations"], rows,
                 extra_note="distinct component_id of outputs/pakemis_atomic_annual.csv with its invariant "
                            "attributes; the schema (pkinv.component/v3) is src/pkinv/core/components.py")



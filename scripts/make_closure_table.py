#!/usr/bin/env python3
"""The closure identities between the products, per gas, as a supplement table generated
from paper_national/figures/rewrite_inputs/data/construction_quantities.csv.

Usage:  python3 scripts/make_closure_table.py [--check]
Writes: paper_national/versions/v3/generated/tab_closure.tex
"""
import csv, io, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "paper_national", "figures", "rewrite_inputs", "data", "construction_quantities.csv")
OUT = os.path.join(ROOT, "paper_national", "versions", "v3", "generated", "tab_closure.tex")
GAS = (("CO2", "CO$_2$"), ("CH4", "CH$_4$"), ("N2O", "N$_2$O"))
def build():
    Q = {(r["node"], r["gas"]): r for r in csv.DictReader(io.open(SRC, encoding="utf-8"))}
    ref = Q[("annual_emissions", "all")]
    L = ["%% GENERATED by scripts/make_closure_table.py from construction_quantities.csv. Do not edit.",
         "\\begin{table}[t]",
         "\\caption{Closure of the spatial products for %s, per gas, in Gg of the native gas: the mass placed on the grid plus the mass retained unallocated equals the national stream ledger. The reference total is %s %s.}" % (ref["period"].replace("FY", "").replace("-", "--"), ref["quantity"], ref["unit"]),
         "\\label{tab:closure}", "\\footnotesize", "\\begin{tabular}{@{}lrrr@{}}", "\\tophline",
         "Gas & Placed (Gg) & Unallocated (Gg) & Ledger (Gg) \\\\", "\\middlehline"]
    for g, tex in GAS:
        L.append("%s & %s & %s & %s \\\\" % (tex, Q[("placed_mass", g)]["quantity"], Q[("unallocated_mass", g)]["quantity"], Q[("ledger_mass", g)]["quantity"]))
    L += ["\\bottomhline", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(L)
def main(argv):
    fresh = build()
    if "--check" in argv:
        held = io.open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        print("closure table: %s" % ("byte-identical" if held == fresh else "DIFFERS")); return 0 if held == fresh else 1
    io.open(OUT, "w", encoding="utf-8").write(fresh); print("wrote", os.path.relpath(OUT, ROOT)); return 0
if __name__ == "__main__": sys.exit(main(sys.argv[1:]))

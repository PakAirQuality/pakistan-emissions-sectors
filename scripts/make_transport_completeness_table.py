"""Generate the transport completeness matrix appendix (S3) from the engine's table.

Same discipline as the residential S3: rendered from outputs/completeness.csv (itself
generated by pkinv.report.completeness and synced to the gap register by test), never
hand-edited, and a test asserts the committed .tex matches a fresh regeneration.

The allowlist is EXPLICIT (code, category) pairs rather than a code filter, because
the transport boundary spans four codes - road, off-road, the 1.A.2 rows its residual
and unresolved diesel actually belong to, and the mobile-A/C IPPU row - and a rename
in the completeness table must fail generation loudly, not silently drop a row.

Usage:  python3 scripts/make_transport_completeness_table.py
"""

from pkinv.assets import asset_path
import csv
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = asset_path(ROOT, "outputs", "completeness.csv")
OUT = asset_path(ROOT, "papers", "transport", "sections", "S3_completeness.tex")

ALLOW = (
    ("1.A.3.b", "Road transport"),
    ("1.A.3.b", "Electric road vehicles"),
    ("1.A.3.c", "Railways"),
    ("1.A.3.a", "Domestic aviation"),
    ("1.A.3.d", "Water-borne navigation - domestic"),
    ("1.A.4.c", "Off-road machinery (tractors and plant)"),
    ("1.A.4.c", "Stationary agriculture/forestry and railway workshops"),
    ("1.A.2", "Captive-generation diesel and furnace oil"),
    ("1.A.2", "Construction and industrial mobile machinery (1A2gvii)"),
    ("2.F.1", "Mobile air-conditioning (road vehicles)"),
    ("(air)", "Air pollutants - road transport"),
    ("(air)", "Air pollutants - road transport cold-start excess"),
    ("(air)", "Air pollutants - road transport evaporative NMVOC"),
    ("(air)", "Air pollutants - road transport non-exhaust PM (tyre, brake and road "
     "wear)"),
)


def _tex(s, width=None):
    s = (s.replace("&", "\\&").replace("%", "\\%").replace("_", "\\_")
         .replace("#", "\\#"))
    if width and len(s) > width:
        s = s[:width - 1].rstrip() + "\\ldots"
    return s


def rows():
    with open(SRC, newline="", encoding="utf-8") as f:
        table = {(r["code"], r["category"]): r for r in csv.DictReader(f)}
    missing = [k for k in ALLOW if k not in table]
    if missing:
        raise SystemExit("completeness rows renamed or removed: %s" % missing)
    return [table[k] for k in ALLOW]


def render():
    lines = [
        "% GENERATED by scripts/make_transport_completeness_table.py - do not",
        "% hand-edit; a test asserts this file matches the engine's completeness "
        "table.",
        "% " + "=" * 75,
        "\\section{The Transport-Boundary Completeness Matrix}",
        "\\label{app:completeness}",
        "% " + "=" * 75,
        "",
        "Every category--gas combination on the transport boundary, with its IPCC",
        "notation key and the justification the engine carries. The boundary spans",
        "four reporting codes deliberately: the diesel this sector's residual class",
        "and unresolved claimants actually belong to sits in 1.A.2, and the vehicle",
        "fleet's refrigerant leakage in IPPU 2.F.1. Generated from the same",
        "completeness table the national inventory publishes, which is itself synced",
        "to the gap register by test.",
        "",
        # longtable: at full justification width this matrix is taller than a page,
        # and a float that cannot fit is deferred to the end of the document.
        "{\\scriptsize",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{longtable}{@{}l>{\\raggedright\\arraybackslash}p{0.15\\linewidth}c>{\\raggedright\\arraybackslash}p{0.11\\linewidth}>{\\raggedright\\arraybackslash}p{0.42\\linewidth}@{}}",
        "\\caption{The transport-boundary completeness matrix, generated from the",
        "engine (\\texttt{outputs/completeness.csv}, explicit allowlist). E =",
        "estimated, IE = included elsewhere, NE = not estimated (each NE row has a",
        "gap-register entry stating what would resolve it), NO = not occurring.}",
        "\\label{tab:completeness1a3b} \\\\",
        "\\toprule",
        "\\textbf{Code} & \\textbf{Category} & \\textbf{Key} & \\textbf{Gases} & "
        "\\textbf{Justification (abridged)} \\\\",
        "\\midrule",
        "\\endfirsthead",
        "\\multicolumn{5}{@{}l}{\\emph{Table \\thetable{} continued}} \\\\",
        "\\toprule",
        "\\textbf{Code} & \\textbf{Category} & \\textbf{Key} & \\textbf{Gases} & "
        "\\textbf{Justification (abridged)} \\\\",
        "\\midrule",
        "\\endhead",
        "\\bottomrule",
        "\\endfoot",
    ]
    for r in rows():
        just = _tex(re.sub(r"\s+", " ", r["justification"]).strip(), 900)
        lines.append("%s & %s & %s & %s & %s \\\\[2pt]"
                     % (_tex(r["code"]), _tex(r["category"], 70), r["notation_key"],
                        _tex(r["gas"], 40).replace("/", "/\\allowbreak "), just))
    lines += [
        "\\end{longtable}}",
        "",
    ]
    return "\n".join(lines)


def main():
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(render())
    print("wrote %s (%d rows)" % (OUT, len(rows())))


if __name__ == "__main__":
    main()

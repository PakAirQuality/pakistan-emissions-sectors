"""Generate the waste completeness matrix appendix (S4) from the engine's table.

Same discipline as the residential and transport papers: the completeness matrix is
rendered from outputs/completeness.csv (itself generated by pkinv.report.completeness
and synced to the gap register by test), never hand-edited, and a test asserts the
committed .tex matches a fresh regeneration. Every IPCC waste category appears with a
notation key - including 4.B and 4.C.1, which occur in Pakistan and are NE here, so
their absence from the estimate reads as a declared gap rather than silence.

Usage:  python3 scripts/make_waste_completeness_table.py
"""

from pkinv.assets import asset_path
import csv
import os
import re
from pkinv.core.io import read_rows

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = asset_path(ROOT, "outputs", "completeness.csv")
OUT = asset_path(ROOT, "papers", "waste", "sections", "S4_completeness.tex")


def _tex(s, width=None):
    s = (s.replace("&", "\\&").replace("%", "\\%").replace("_", "\\_")
         .replace("#", "\\#"))
    if width and len(s) > width:
        s = s[:width - 1].rstrip() + "\\ldots"
    return s


def rows():
    return [r for r in read_rows(SRC, comments=False) if r["code"].startswith("4.")]


def render():
    lines = [
        "% GENERATED by scripts/make_waste_completeness_table.py - do not",
        "% hand-edit; a test asserts this file matches the engine's completeness table.",
        "% " + "=" * 75,
        "\\section{Supplementary Table: the IPCC sector-4 completeness matrix}",
        "\\label{app:completeness}",
        "% " + "=" * 75,
        "",
        "Every IPCC waste category, with its notation key (E estimated, NE not",
        "estimated, IE included elsewhere) and the justification the engine carries",
        "for every non-E entry. Generated from the same completeness table the",
        "national inventory publishes, which is itself synced bidirectionally to the",
        "gap register by test -- an NE row without a register entry, or a register",
        "entry without an NE row, fails the build.",
        "",
        "\\begin{table*}[htbp]",
        "\\centering",
        "\\scriptsize",
        # 0.43, not 0.44: the four fixed columns plus 0.44\linewidth plus eight
        # \tabcolsep came to 522.77pt in a 522pt full-width float, and the last
        # column printed 0.8pt off the page.
        "\\begin{tabular}{@{}llclp{0.43\\linewidth}@{}}",
        "\\toprule",
        "\\textbf{Code} & \\textbf{Category} & \\textbf{Key} & \\textbf{Gases} & "
        "\\textbf{Justification (abridged)} \\\\",
        "\\midrule",
    ]
    for r in rows():
        cat = _tex(r["category"], 60)
        just = _tex(re.sub(r"\s+", " ", r["justification"]).strip(), 260)
        lines.append("%s & %s & %s & %s & %s \\\\[2pt]"
                     % (r["code"], cat, r["notation_key"], _tex(r["gas"]), just))
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\caption{The waste-sector completeness matrix, generated from the engine",
        "(\\texttt{outputs/completeness.csv}, sector-4 rows). Full justifications are",
        "in the generated national table; each NE row names its gap-register entry.}",
        "\\label{tab:completeness}",
        "\\end{table*}",
        "",
    ]
    return "\n".join(lines)


def main():
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(render())
    print("wrote %s (%d rows)" % (OUT, len(rows())))


if __name__ == "__main__":
    main()

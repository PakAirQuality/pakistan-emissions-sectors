"""Generate the transport factor/parameter provenance appendix (S2) from the data files.

Same discipline as the residential S2: every factor, control total and parameter the
engine reads is rendered from data/emission_factors.csv, data/transport_params.csv and
data/activity/transport/emission_factors_gkm.csv - never hand-typed - and a test
asserts the committed .tex matches a fresh regeneration. The g/km air factors carry
the honest source label: Punjab-workbook transcription, no primary citation located.

Usage:  python3 scripts/make_transport_factor_table.py
"""

from pkinv.assets import asset_path
import csv
import os
import re
from pkinv.core.io import read_rows

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EF = asset_path(ROOT, "data", "emission_factors.csv")
PARAMS = asset_path(ROOT, "data", "transport_params.csv")
GKM = asset_path(ROOT, "data", "activity", "transport", "emission_factors_gkm.csv")
OUT = asset_path(ROOT, "papers", "transport", "sections", "S2_factors.tex")

EF_CATEGORIES = ("transport_fuel_supply", "transport_fuel_supply_legacy",
                 "transport_fuel_supply_pes12", "transport_ncv",
                 "transport_fuel_co2", "transport_fuel_ch4", "transport_fuel_n2o",
                 "offroad_machinery_co2", "offroad_machinery_ch4",
                 "offroad_machinery_n2o")
CLASSES = ("2W", "3W", "4W1", "4W2", "4WT", "LDV", "BUS", "HDV", "NRV")


def _tex(s, width=None):
    s = (s.replace("&", "\\&").replace("%", "\\%").replace("_", "\\_")
         .replace("#", "\\#"))
    if width and len(s) > width:
        s = s[:width - 1].rstrip() + "\\ldots"
    return s


def _fmt(v):
    f = float(v)
    return ("%d" % f) if f == int(f) and abs(f) >= 1 else ("%g" % f)


def ef_rows():
    with open(EF, newline="", encoding="utf-8") as f:
        rows = [r for r in csv.DictReader(f) if r["category"] in EF_CATEGORIES]
    order = {c: i for i, c in enumerate(EF_CATEGORIES)}
    return sorted(rows, key=lambda r: (order[r["category"]], r["item"]))


def params():
    return {r["param"]: r for r in read_rows(PARAMS, comments=False)}


EMEP = asset_path(ROOT, "data", "activity", "transport", "emep_tier1_road_air.csv")
CLASS_MAP = asset_path(ROOT, "data", "activity", "transport", "emep_class_map.csv")
SULFUR = asset_path(ROOT, "data", "activity", "transport", "fuel_sulfur_by_year.csv")


def _csv(path):
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(r for r in f if not r.startswith("#")))


def emep_rows():
    return _csv(EMEP)


def class_map_rows():
    return _csv(CLASS_MAP)


def sulfur_rows():
    return _csv(SULFUR)


def gkm_rows():
    with open(GKM, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    # drop all-zero rows (fuel/class combinations the fleet model never produces).
    # Only the pollutant columns are numeric - the file also carries provenance
    # columns, which float() would choke on.
    pollutants = [k for k in rows[0]
                  if k not in ("ei_class", "fuel", "source", "provenance_class", "note")]
    keep = [r for r in rows if any(float(r[k]) for k in pollutants)]
    return keep


def _breakable(text):
    """Long file paths are one unbreakable token to TeX. Allow a line break after
    the separators so a source string wraps inside its column instead of overrunning
    it - the supplement's whole purpose is to print these strings in full."""
    return text.replace("/", "/\\allowbreak ").replace("\\_", "\\_\\allowbreak ")


def render():
    p = params()
    lines = [
        "% GENERATED by scripts/make_transport_factor_table.py - do not hand-edit;",
        "% a test asserts this file matches a fresh regeneration from the data files.",
        "% " + "=" * 75,
        "\\section{Factors, Controls and Parameters with Provenance}",
        "\\label{app:factors}",
        "% " + "=" * 75,
        "",
        "Every factor, control total and model parameter the engine reads, rendered",
        "from the same CSV files the code reads (\\texttt{data/emission\\_factors.csv},",
        "\\texttt{data/transport\\_params.csv},",
        "\\texttt{data/activity/transport/emep\\_tier1\\_road\\_air.csv},",
        "\\texttt{data/activity/transport/emep\\_class\\_map.csv},",
        "\\texttt{data/activity/transport/fuel\\_sulfur\\_by\\_year.csv} and the",
        "superseded \\texttt{data/activity/transport/emission\\_factors\\_gkm.csv}) so the table",
        "cannot drift from the calculation.",
        "",
        # longtable, not a float: at full source-string width this runs past one
        # page, and a float that cannot fit its page is deferred to the end of the
        # document - which is how the previous edition ended up printing its
        # appendix tables several pages after the headings that introduced them.
        "{\\scriptsize",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{longtable}{@{}>{\\raggedright\\arraybackslash}p{0.12\\linewidth}>{\\raggedright\\arraybackslash}p{0.13\\linewidth}r>{\\raggedright\\arraybackslash}p{0.09\\linewidth}r>{\\raggedright\\arraybackslash}p{0.42\\linewidth}@{}}",
        "\\caption{Emission factors, fuel controls and parameters. The",
        "\\texttt{fuel\\_supply} rows are the OCAC Road customer-class controls;",
        "the \\texttt{supply\\_legacy} rows are the superseded PES-derived pair,",
        "retained for the \\texttt{legacy\\_pes\\_control} scenario with their",
        "provenance error documented, and \\texttt{supply\\_pes12} is that note's",
        "arithmetic done correctly at its (wrong) FY2025 vintage. The",
        "household-generator carve-out is relayed from the residential sector and",
        "the full claimant structure appears in",
        "\\texttt{outputs/transport\\_fuel\\_ledger\\_2024.csv}.}",
        "\\label{tab:s2factors} \\\\",
        "\\toprule",
        "\\textbf{Group} & \\textbf{Item} & \\textbf{Value} & \\textbf{Unit} & "
        "\\textbf{$\\pm$\\%} & \\textbf{Source} \\\\",
        "\\midrule",
        "\\endfirsthead",
        "\\multicolumn{6}{@{}l}{\\emph{Table \\thetable{} continued}} \\\\",
        "\\toprule",
        "\\textbf{Group} & \\textbf{Item} & \\textbf{Value} & \\textbf{Unit} & "
        "\\textbf{$\\pm$\\%} & \\textbf{Source} \\\\",
        "\\midrule",
        "\\endhead",
        "\\bottomrule",
        "\\endfoot",
    ]
    for r in ef_rows():
        lines.append("%s & %s & %s & %s & %s & %s \\\\"
                     % (_breakable(_tex(r["category"].replace("transport_", "").replace(
                         "offroad_machinery", "off-road"))),
                        _breakable(_tex(r["item"])), _fmt(r["value"]),
                        _breakable(_tex(r["unit"])),
                        _fmt(r["uncert_pct"]) if r["uncert_pct"] else "--",
                        _breakable(_tex(re.sub(r"\s+", " ", r["source"]).strip(), 400))))
    lines += ["\\midrule"]
    for key in ("activity_uncert", "cng_activity_uncert", "cng_hhv_btu_per_scf",
                "cng_gross_to_net", "suv_share_start", "suv_share_end"):
        r = p[key]
        lines.append("param & %s & %s & %s & %s & %s \\\\"
                     % (_breakable(_tex(key)), _fmt(r["value"]),
                        _breakable(_tex(r["unit"], 48)),
                        _fmt(r["uncert_pct"]) if r["uncert_pct"] else "--",
                        _breakable(_tex(re.sub(r"\s+", " ", r["source"]).strip(), 400))))
    lines += [
        "\\end{longtable}}",
        "",
        "\\begin{table}[!htbp]",
        "\\centering",
        "\\scriptsize",
        "\\begin{tabular}{@{}lrr@{}}",
        "\\toprule",
        "\\textbf{Class} & \\textbf{Weibull $\\beta$} & \\textbf{Median life "
        "(yr)} \\\\",
        "\\midrule",
    ]
    for cls in CLASSES:
        lines.append("%s & %s & %s \\\\"
                     % (cls, _fmt(p["weibull_beta_%s" % cls]["value"]),
                        _fmt(p["weibull_life_%s" % cls]["value"])))
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\caption{Survival-model parameters by class (Naveed 2024, \\S3.7.3",
        "Table~5, adopting the Guttikunda 2024 high-survival scenario); $\\beta$ at",
        "$\\pm$25\\%, life at $\\pm$20\\%.}",
        "\\label{tab:s2weibull}",
        "\\end{table}",
        "",
        "\\begin{table}[!htbp]",
        "\\centering",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{@{}lllrrrl@{}}",
        "\\toprule",
        "\\textbf{Process} & \\textbf{Category} & \\textbf{Fuel} & "
        "\\textbf{Value} & \\textbf{min} & \\textbf{max} & \\textbf{Unit} \\\\",
        "\\midrule",
    ]
    POL_TEX = {"NOx": "NO$_x$", "SO2": "SO$_2$", "NH3": "NH$_3$",
               "PM2.5": "PM$_{2.5}$", "PM10": "PM$_{10}$"}
    for r in emep_rows():
        pol = POL_TEX.get(r["pollutant"], r["pollutant"])
        lines.append("%s %s & %s & %s & %s & %s & %s & %s \\\\"
                     % (r["process"].replace("_", " "), pol, r["emep_category"],
                        r["fuel"] or "--", _fmt(r["value"]),
                        _fmt(r["lo"]) if r["lo"] else "--",
                        _fmt(r["hi"]) if r["hi"] else "--",
                        r["unit"].replace("_", " ")))
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\caption{EMEP/EEA guidebook 2023 Tier~1 road-transport factors, transcribed",
        "from the held chapter PDFs (road transport Update 2025 Tables 3-5/3-6/3-7/3-11;",
        "gasoline evaporation Table 3-1 at the 20--35\\,\\si{\\celsius} band; tyre-and-brake",
        "and road-surface wear Tables 3-1/3-2), each cell re-checked against the source",
        "text by \\texttt{scripts/check\\_transcriptions.py}. min/max span uncontrolled to",
        "2010-current technology and are carried as each row's uncertainty. Exhaust PM is",
        "PM$_{2.5}$ by the chapter's own statement. f-BC rows are fractions of exhaust",
        "PM$_{2.5}$, components not additions.}",
        "\\label{tab:s2emep}",
        "\\end{table}",
        "",
        "\\begin{table}[!htbp]",
        "\\centering",
        "\\scriptsize",
        "\\begin{tabular}{@{}lllll@{}}",
        "\\toprule",
        "\\textbf{Class} & \\textbf{Fuel} & \\textbf{Tier~1 category} & "
        "\\textbf{Tier~1 fuel} & \\textbf{Declared proxy} \\\\",
        "\\midrule",
    ]
    for r in class_map_rows():
        lines.append("%s & %s & %s & %s & %s \\\\"
                     % (r["ei_class"], r["fuel"], r["emep_category"], r["emep_fuel"],
                        _tex(r["proxy_note"][:60] + ("\\dots" if len(r["proxy_note"]) > 60 else "")) if r["proxy_note"] else "--"))
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\caption{The declared bridge from the fleet model's classes to the Tier~1",
        "categories (\\texttt{emep\\_class\\_map.csv}): a cell without a published",
        "Tier~1 factor in the held chapters takes a named proxy, never a silent one.}",
        "\\label{tab:s2classmap}",
        "\\end{table}",
        "",
        "\\begin{table}[!htbp]",
        "\\centering",
        "\\scriptsize",
        "\\begin{tabular}{@{}llrrrl@{}}",
        "\\toprule",
        "\\textbf{Year} & \\textbf{Fuel} & \\textbf{ppm} & \\textbf{lo} & "
        "\\textbf{hi} & \\textbf{Basis} \\\\",
        "\\midrule",
    ]
    for r in sulfur_rows():
        lines.append("%s & %s & %s & %s & %s & %s \\\\"
                     % (r["fiscal_end_year"], r["fuel"], _fmt(r["ppm_central"]),
                        _fmt(r["ppm_lo"]), _fmt(r["ppm_hi"]),
                        _tex(r["basis"][:64] + ("\\dots" if len(r["basis"]) > 64 else ""))))
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\caption{The declared road-fuel sulfur regime by fiscal year",
        "(\\texttt{fuel\\_sulfur\\_by\\_year.csv}), behind the stoichiometric SO$_2$;",
        "declared from the cited import-mandate record, not measured at the pump",
        "(gap \\texttt{road-fuel-sulfur}). CNG carries no sulfur row: pipeline gas is",
        "desulfurised and the absence is an absence, not a zero.}",
        "\\label{tab:s2sulfur}",
        "\\end{table}",
        "",
        "\\begin{table}[!htbp]",
        "\\centering",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{@{}llrrrrrrr@{}}",
        "\\toprule",
        "\\textbf{Class} & \\textbf{Fuel} & NO$_x$ & CO & NMVOC & PM$_{2.5}$ & "
        "PM$_{10}$ & SO$_2$ & NH$_3$ \\\\",
        "\\midrule",
    ]
    for r in gkm_rows():
        lines.append("%s & %s & %s \\\\"
                     % (r["ei_class"], r["fuel"],
                        " & ".join(_fmt(r[k]) for k in
                                   ("NOx", "CO", "NMVOC", "PM2.5", "PM10", "SO2",
                                    "NH3"))))
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\caption{SUPERSEDED per-kilometre factors (g/km), retained for the",
        "old-vs-new comparison in the air appendix: these are transcriptions of the",
        "Punjab emissions workbook's values, for which no primary citation was ever",
        "located, and the EMEP/EEA Tier~1 tables above replaced them as the layer's",
        "factor basis. Nothing canonical reads this table any longer.",
        "NMVOC is non-methane VOC; NO$_x$ is NO$_2$-equivalent mass, the",
        "inventory-wide basis.",
        "Rows the fleet model never produces (all-zero) are omitted.}",
        "\\label{tab:s2gkm}",
        "\\end{table}",
        "",
    ]
    return "\n".join(lines)


def main():
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(render())
    print("wrote %s (%d factor rows, %d g/km rows)"
          % (OUT, len(ef_rows()), len(gkm_rows())))


if __name__ == "__main__":
    main()

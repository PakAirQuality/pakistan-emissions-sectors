#!/usr/bin/env python3
"""The supplement's five-class validation table, generated from the summary product.

Usage:  python3 scripts/make_five_classes_table.py [--check]
Writes: paper_national/versions/v3/generated/tab_five_classes.tex
"""
import csv, io, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "outputs", "pakemis_validation_five_classes_summary.csv")
OUT = os.path.join(ROOT, "paper_national", "versions", "v3", "generated", "tab_five_classes.tex")
LABEL = {"partially independent benchmark": "Partially independent benchmark",
         "independent compilation (another inventory; not an observation of emissions)": "Independent compilation (another inventory, not an observation)",
         "calibration (fitted to the comparator; cannot validate it)": "Calibration (fitted to the comparator; cannot validate it)",
         "shares activity or factors with the estimate": "Shares activity or factors with the estimate",
         "internal consistency / accounting identity": "Internal consistency or accounting identity",
         "declared absence (no check performed)": "Declared absence (no check performed)",
         "not a comparison": "Not a comparison", "TOTAL": "All catalogue entries"}
def build():
    rows = [r for r in csv.DictReader(l for l in io.open(SRC, encoding="utf-8") if not l.startswith("#"))]
    L = ["%% GENERATED by scripts/make_five_classes_table.py from pakemis_validation_five_classes_summary.csv. Do not edit.",
         "\\begin{table}[t]",
         "\\caption{The validation catalogue regrouped by what each entry can establish. The count of entries is a register count, not a count of validations; the class of every entry is in \\texttt{outputs/pakemis\\_validation\\_five\\_classes.csv}.}",
         "\\label{tab:five_classes}", "\\footnotesize", "\\begin{tabular}{@{}>{\\raggedright\\arraybackslash}p{6.0cm}r@{}}", "\\tophline",
         "Class & Entries \\\\", "\\middlehline"]
    for r in rows:
        if r["five_class"] == "TOTAL":
            L.append("\\middlehline")
        L.append("%s & %s \\\\" % (LABEL[r["five_class"]], r["entries"]))
    L += ["\\bottomhline", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(L)
def main(argv):
    fresh = build()
    if "--check" in argv:
        held = io.open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        print("five classes table: %s" % ("byte-identical" if held == fresh else "DIFFERS")); return 0 if held == fresh else 1
    io.open(OUT, "w", encoding="utf-8").write(fresh); print("wrote", os.path.relpath(OUT, ROOT)); return 0
if __name__ == "__main__": sys.exit(main(sys.argv[1:]))

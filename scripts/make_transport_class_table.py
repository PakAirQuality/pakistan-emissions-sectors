"""Generate the class-parameter appendix (S5) and its CSV from the engine.

Every quantity that determines the class split, in one place: per-class registered
stock, survival-weighted active fleet, annual kilometres, survival parameters, fuel
splits, district-cell counts, and the resulting within-fuel vehicle-kilometre
weights - including the single number that makes the paper's KNOWN-FLAW paragraph
concrete (the two-wheeler share of the petrol control), and the off-road partition
share shown with its actual numerator and denominator. Computed from the engine at
generation time; a test asserts the committed .tex matches a fresh regeneration and
that the displayed off-road share equals road.off_road_TJ's.

Usage:  python3 scripts/make_transport_class_table.py
Writes: papers/transport/sections/S5_classes.tex,
        outputs/transport_class_parameters_<year>.csv,
        outputs/transport_class_fuel_weights_<year>.csv
"""
import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))

from pkinv.assets import asset_path

from pkinv.sectors.transport import fleet, road  # noqa: E402
from pkinv.sectors.transport.data import TransportData  # noqa: E402

OUT_TEX = asset_path(ROOT, "papers", "transport", "sections", "S5_classes.tex")
OUT_CSV = asset_path(ROOT, "outputs",
                       "transport_class_parameters_%d.csv" % TransportData().year)
OUT_WEIGHTS_CSV = asset_path(ROOT, "outputs",
                               "transport_class_fuel_weights_%d.csv" % TransportData().year)

LABELS = {"2W": "Two-wheelers", "3W": "Three-wheelers", "4W1": "Cars (small)",
          "4W2": "Cars (large/SUV)", "4WT": "Taxis", "LDV": "Light duty",
          "BUS": "Buses", "HDV": "Heavy duty", "NRV": "Off-road (mixed)"}


def compute(data=None):
    data = TransportData() if data is None else data
    # The FLEET year, not the control year: the registration panel's last year is
    # partial (see TransportData.fleet_year), and asking for it drops whole vehicle
    # classes out of the table with no error.
    year = data.fleet_year()
    per_class = {}
    for cls in fleet.CLASSES:
        per_class[cls] = {"active": 0.0, "registered": 0.0, "cells": 0,
                          "capped": 0}
    for province, district, cls in data.cells(year):
        series = data.stock_series(province, district, cls)
        if year not in series:
            continue
        active, was_capped = fleet.active_fleet(
            series, data.p("weibull_beta_%s" % cls),
            data.p("weibull_life_%s" % cls), year)
        per_class[cls]["active"] += active
        per_class[cls]["registered"] += series[year]
        per_class[cls]["cells"] += 1
        per_class[cls]["capped"] += 1 if was_capped else 0

    vkt, _cells, _capped = road.effective_vkt(data, year)
    shares = road._shares(data, vkt)
    rows = []
    for cls in fleet.CLASSES:
        d = per_class[cls]
        split = data.split_for(cls, year)
        rows.append({
            "ei_class": cls, "label": LABELS[cls],
            "active_fleet": round(d["active"], 1),
            "registered": round(d["registered"], 0),
            "active_over_registered": round(d["active"] / d["registered"], 4)
            if d["registered"] else "",
            "vkt_km_per_vehicle": data.vkt_for(cls, year),
            "weibull_beta": data.p("weibull_beta_%s" % cls),
            "weibull_life_yr": data.p("weibull_life_%s" % cls),
            "fuel_split": "; ".join("%s %.4g" % (f, s)
                                    for f, s in sorted(split.items()) if s),
            "district_cells": d["cells"], "cells_capped": d["capped"],
        })
    # The published weights are energy, not distance: the MJ/km midpoint is printed
    # beside the kilometres it multiplies, so a reader can rebuild every weight.
    weights = [{"ei_class": cls, "fuel": f,
                "vkt_vehicle_km": round(km, 0),
                "mjkm_mid": data.mjkm(cls, f),
                "energy_MJ": round(km * data.mjkm(cls, f), 0),
                "within_fuel_weight": round(shares[(cls, f)], 6)}
               for (cls, f), km in sorted(vkt.items())]
    energy = {k: v * data.mjkm(k[0], k[1]) for k, v in vkt.items() if k[1] == "Diesel"}
    off_mj = sum(v for k, v in energy.items() if k[0] == road.OFF_ROAD)
    on_mj = sum(v for k, v in energy.items() if k[0] != road.OFF_ROAD)
    derivation = {"off_MJ": off_mj, "on_diesel_MJ": on_mj,
                  "share": off_mj / (off_mj + on_mj),
                  "off_road_TJ": road.off_road_TJ(data)}
    return rows, weights, derivation


def _fmt(v):
    f = float(v)
    return ("%d" % f) if f == int(f) and abs(f) >= 1 else ("%g" % f)


def render():
    rows, weights, der = compute()
    lines = [
        "% GENERATED by scripts/make_transport_class_table.py - do not hand-edit;",
        "% a test asserts this file matches a fresh regeneration from the engine.",
        "% " + "=" * 75,
        "\\section{The Class-Level Calculation, in Full}",
        "\\label{app:classes}",
        "% " + "=" * 75,
        "",
        "Every quantity that determines the class split, including the declared",
        "energy intensities that weight it. The within-fuel weights are the",
        "$s_{c,f}$ of the main paper's methods section: vehicle-kilometres times",
        "MJ/km, normalised within each fuel over \\emph{all} classes including",
        "off-road, which is the deliberate normalisation that lets the two",
        "categories partition one diesel quantity. Because the weights sum to one",
        "by construction, the intensities move composition and never magnitude.",
        "Machine-readable: \\texttt{outputs/transport\\_class\\_parameters\\_2024.csv}.",
        "",
        "\\begin{table}[!htbp]",
        "\\centering",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{@{}llrrrrrrlrr@{}}",
        "\\toprule",
        "\\textbf{Class} & & \\textbf{Active fleet} & \\textbf{Registered} & "
        "\\textbf{A/R} & \\textbf{km/veh} & \\textbf{$\\beta$} & \\textbf{Life} & "
        "\\textbf{Fuel split} & \\textbf{Cells} & \\textbf{Capped} \\\\",
        "\\midrule",
    ]
    for r in rows:
        lines.append("%s & %s & %s & %s & %s & %s & %s & %s & %s & %d & %d \\\\"
                     % (r["ei_class"], r["label"],
                        "{:,.0f}".format(r["active_fleet"]),
                        "{:,.0f}".format(r["registered"]),
                        _fmt(r["active_over_registered"]),
                        "{:,.0f}".format(r["vkt_km_per_vehicle"]),
                        _fmt(r["weibull_beta"]), _fmt(r["weibull_life_yr"]),
                        r["fuel_split"].replace("Petrol", "P").replace(
                            "Diesel", "D").replace("CNG", "C"),
                        r["district_cells"], r["cells_capped"]))
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\caption{Class parameters, FY2023--24 (registration panel 2023, a declared borrowed shape): survival-weighted active fleet against "
        "registered stock, annual kilometres, Weibull parameters (Naveed 2024, "
        "adopting Guttikunda 2024), fuel splits, and the district cells the "
        "Weibull cap binds in.}",
        "\\label{tab:classparams}",
        "\\end{table}",
        "",
        "\\begin{table}[!htbp]",
        "\\centering",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{@{}llrrrr@{}}",
        "\\toprule",
        "\\textbf{Class} & \\textbf{Fuel} & \\textbf{Vehicle-km/yr} & "
        "\\textbf{MJ/km} & \\textbf{Energy (MJ)} & \\textbf{Weight} \\\\",
        "\\midrule",
    ]
    for w in weights:
        lines.append("%s & %s & %.3e & %s & %.3e & %.6f \\\\"
                     % (w["ei_class"], w["fuel"], w["vkt_vehicle_km"],
                        _fmt(w["mjkm_mid"]), w["energy_MJ"],
                        w["within_fuel_weight"]))
    tw = next(w["within_fuel_weight"] for w in weights
              if w["ei_class"] == "2W" and w["fuel"] == "Petrol")
    # The distance-only counterpart, recomputed from the same rows rather than
    # frozen as a literal: the ninth review caught the frozen "0.7858" - a
    # PRIOR anchoring's value that survived the rc5 period rebuild while the
    # energy weight moved under it.
    petrol_vkt = [w["vkt_vehicle_km"] for w in weights if w["fuel"] == "Petrol"]
    dw = next(w["vkt_vehicle_km"] for w in weights
              if w["ei_class"] == "2W" and w["fuel"] == "Petrol") / sum(petrol_vkt)
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\caption{The within-fuel weights $s_{c,f}$, with the kilometres and the "
        "declared MJ/km midpoints they are built from. The two-wheeler petrol "
        "weight is %.4f: %.1f\\%% of the petrol control. On distance alone it "
        "would be %.4f, and the difference between those two numbers is the whole "
        "correction -- a motorcycle-kilometre and a car-kilometre are not the same "
        "quantity of petrol. The intensities are declared engineering judgement, "
        "not Pakistani measurement, which is why they are confined to a "
        "normalisation that cannot move the sector total.}" % (tw, 100 * tw, dw),
        "\\label{tab:classweights}",
        "\\end{table}",
        "",
        "The off-road partition share, with its actual inputs -- energy, not",
        "distance, because the same normalisation that splits the on-road classes",
        "sets this share:",
        "\\begin{equation*}",
        "s_{\\text{offroad}} = \\frac{%.4g}{%.4g + %.4g} = %.5f,"
        % (der["off_MJ"], der["off_MJ"], der["on_diesel_MJ"], der["share"]),
        "\\end{equation*}",
        "in megajoules of declared fleet energy, which carves "
        "\\SI{%.0f}{\\tera\\joule} from the Road-row diesel control. The numerator "
        "is the off-road class's %s active vehicles at \\SI{%.0f}{\\kilo\\metre} "
        "each at \\SI{%s}{\\mega\\joule\\per\\kilo\\metre}; on distance alone the "
        "share was 0.09998, and it falls because off-road machinery burns LESS "
        "per kilometre than the on-road diesel fleet average (7 MJ/km against "
        "roughly 9.5, a mean dominated by buses and heavy goods vehicles) -- "
        "weighting by energy shrinks the off-road share and moves diesel back "
        "to the road category. The "
        "\\texttt{offroad\\_share\\_5pct} and \\texttt{15pct} scenarios price the "
        "share's softness."
        % (der["off_road_TJ"],
           "{:,.0f}".format(next(r["active_fleet"] for r in rows
                                 if r["ei_class"] == "NRV")),
           next(r["vkt_km_per_vehicle"] for r in rows if r["ei_class"] == "NRV"),
           _fmt(next(w["mjkm_mid"] for w in weights
                     if w["ei_class"] == "NRV" and w["fuel"] == "Diesel"))),
        "",
    ]
    return "\n".join(lines)


def main():
    rows, weights, der = compute()
    os.makedirs(os.path.dirname(OUT_CSV), exist_ok=True)
    # rc41 (D-1): one table per file. The within-fuel weights used to follow the class
    # table in the SAME csv after a blank line - a second header eighteen rows down that
    # every csv reader parsed as eighteen malformed rows of the first table.
    with open(OUT_CSV, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    with open(OUT_WEIGHTS_CSV, "w", newline="", encoding="utf-8") as f:
        w2 = csv.DictWriter(f, fieldnames=list(weights[0].keys()))
        w2.writeheader()
        w2.writerows(weights)
    with open(OUT_TEX, "w", encoding="utf-8") as fh:
        fh.write(render())
    print("wrote %s (%d classes, %d weights), %s and %s"
          % (OUT_TEX, len(rows), len(weights), os.path.relpath(OUT_CSV, ROOT),
             os.path.relpath(OUT_WEIGHTS_CSV, ROOT)))


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""The livestock table: species, population, period, enteric factor, typical mass and
nitrogen excretion, each with its source - generated from the parameter files.

WHY. The supplement states the Tier 1/Tier 2 livestock inputs in prose; the 23rd review
asked for the species x factor x source table. Generated so it cannot drift from
data/activity/agriculture/livestock_2024.csv, data/shared/parameters/emission_factors.csv
and data/sectors/agriculture/parameters/parameters.csv.

Usage:  python3 scripts/make_livestock_factor_table.py [--check]
Writes: paper_national/versions/v3/generated/tab_livestock_factors.tex
"""
import csv
import io
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src"))
from pkinv.assets import asset_path  # noqa: E402
from pkinv.paths import DATA  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "paper_national", "versions", "v3", "generated", "tab_livestock_factors.tex")
SPECIES = (("dairy_cattle", "Dairy cattle", "cattle"), ("other_cattle", "Other cattle", "cattle"),
           ("buffalo", "Buffalo", "buffalo"), ("sheep", "Sheep", "sheep"),
           ("goats", "Goats", "goats"), ("camels", "Camels", "camels"))


def rows(path):
    with io.open(path, encoding="utf-8") as handle:
        return list(csv.DictReader(line for line in handle if not line.startswith("#")))


def esc(s):
    return (s.replace("\\", "\\textbackslash{}").replace("%", "\\%").replace("_", "\\_")
             .replace("&", "\\&").replace("#", "\\#").replace("$", "\\$"))


def short(source):
    """The citation form of a source string: the document, not the note."""
    return source.split(" (")[0].split(";")[0].strip()


def build():
    live = {r["species"]: r for r in rows(asset_path(DATA, "activity", "livestock_2024.csv"))}
    efs = {r["item"]: r for r in rows(asset_path(DATA, "emission_factors.csv")) if r["category"] == "enteric"}
    params = {r["param"]: r for r in rows(asset_path(DATA, "parameters.csv"))}
    dairy = float(params["dairy_cattle_share"]["value"])
    L = ["%% GENERATED by scripts/make_livestock_factor_table.py. Do not edit.",
         "\\begin{table*}[t]",
         "\\caption{Livestock inputs, FY2023--24: population by species, the enteric CH$_4$ factor, "
         "the typical animal mass and the nitrogen-excretion rate, with the source of each. Cattle "
         "are split into dairy and other at the FAOSTAT milk-animal share (%.3f); populations are the "
         "PBS 7th Agricultural Census 2024 enumeration. Factors are IPCC 2006 defaults; typical masses "
         "are Pakistan-specific values whose provenance class is stated in the parameter file.}"
         % dairy,
         "\\label{tab:livestock_factors}", "\\footnotesize",
         "\\begin{tabular}{@{}lrlrrrl@{}}", "\\tophline",
         "Species & Head (M) & Population basis & EF (kg CH$_4$ hd$^{-1}$ yr$^{-1}$) & $\\pm$\\% & "
         "Mass (kg) & N$_{ex}$ (kg N (1000 kg)$^{-1}$ d$^{-1}$) \\\\", "\\middlehline"]
    for key, label, pop in SPECIES:
        head = float(live[pop]["head_value"])
        if key == "dairy_cattle":
            head *= dairy
        elif key == "other_cattle":
            head *= 1 - dairy
        ef = efs[key]
        tam = params["tam_" + key]
        nex = params["nex_rate_" + key]
        L.append("%s & %.2f & %s & %s & %s & %s & %s \\\\" % (
            label, head / 1e6, esc(live[pop]["activity_basis"].replace("_", " ")),
            ef["value"], ef["uncert_pct"], tam["value"], nex["value"]))
    L += ["\\bottomhline", "\\end{tabular}", "",
          "\\smallskip\\noindent\\footnotesize Sources. Populations: %s (%s). Enteric factors: %s. "
          "Typical masses: %s. Excretion rates: %s." % (
              esc(short(live["cattle"]["source"])), esc(live["cattle"]["reference_period"]),
              esc("; ".join(sorted({short(e["source"]) for e in efs.values()}))),
              esc("; ".join(sorted({short(params["tam_" + k]["source"]) for k, _, _ in SPECIES}))),
              esc("; ".join(sorted({short(params["nex_rate_" + k]["source"]) for k, _, _ in SPECIES})))),
          "\\end{table*}", ""]
    return "\n".join(L)


def main(argv):
    fresh = build()
    if "--check" in argv:
        held = io.open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        print("livestock table: %s" % ("byte-identical" if held == fresh else "DIFFERS"))
        return 0 if held == fresh else 1
    io.open(OUT, "w", encoding="utf-8").write(fresh)
    print("wrote", os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

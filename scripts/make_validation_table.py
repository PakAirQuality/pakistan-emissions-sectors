#!/usr/bin/env python3
"""The paper's compact table of measured validation, rendered from its product (rc69).

Reads outputs/pakemis_validation_measured.csv (pkinv.report.validation_measured) and writes
the LaTeX table the evaluation section inputs. No number is typed here; every cell is the
product's own, so the table cannot drift from what the release measured.

Usage:  python3 scripts/make_validation_table.py [--check]
Writes: paper_national/versions/v3/generated/tab_validation_measured.tex
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))

from pkinv.core.io import read_rows  # noqa: E402

SRC = os.path.join(ROOT, "outputs", "pakemis_validation_measured.csv")
OUT = os.path.join(ROOT, "paper_national", "versions", "v3", "generated",
                   "tab_validation_measured.tex")
GROUPS = (("source parsing", "Source parsing"), ("closure", "Closure"),
          ("reproduction", "Reproduction"))


def _tex(text):
    return (text.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_")
            .replace("PM2.5", "PM$_{2.5}$").replace("CO2e", "CO$_2$e"))


def _closing(row):
    if row["closing"] and row["closing_of"]:
        return "%s / %s" % (row["closing"], row["closing_of"])
    return "--"


def render(rows):
    lines = [
        "%% GENERATED by scripts/make_validation_table.py from "
        "outputs/pakemis_validation_measured.csv. Do not edit.",
        r"\begin{table*}[t]",
        r"\caption{Measured validation in the release. Records: what each check read; "
        r"rejected: rows quarantined unrepaired or files that differed; closing: units that "
        r"close their control, of all units; residual: the largest absolute closure "
        r"residual, in the unit shown. The fifteen gridded rows that do not close are declared "
        r"divergences of the three Islamabad International Airport LTO streams, which are in "
        r"Islamabad Capital Territory in the provincial share table and in Attock, Punjab, on "
        r"the grid. The rebuild rows compare every product file with the released one (rc68): "
        r"closing counts files byte-identical to the release, the remainder being files seeded "
        r"from the release and manuscripts the rebuild does not compile. The test row is the "
        r"published canonical run. Sources and "
        r"notes for every row are in \texttt{pakemis\_validation\_measured.csv}.}",
        r"\label{tab:validation_measured}",
        r"\small",
        r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lrrrl@{}}",
        r"\tophline",
        r"Check & Records & Rejected & Closing & Largest residual \\",
        r"\middlehline",
    ]
    for group, title in GROUPS:
        members = [r for r in rows if r["group"] == group]
        if not members:
            raise ValueError("no rows for group %r" % group)
        lines.append(r"\multicolumn{5}{@{}l}{\textit{%s}} \\" % title)
        for r in members:
            residual = (r"\num{%s} %s" % (r["max_abs_residual"], _tex(r["residual_unit"]))
                        if r["max_abs_residual"] else "--")
            lines.append(" & ".join([
                _tex(r["check"]), "{:,}".format(int(r["records_checked"])).replace(",", r"\,"),
                r["failed_or_quarantined"] or "--", _closing(r), residual]) + r" \\")
    lines += [r"\bottomhline", r"\end{tabular*}", r"\end{table*}"]
    return "\n".join(lines) + "\n"


def main(argv):
    text = render(read_rows(SRC))
    if "--check" in argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            print("stale: %s; run python3 scripts/make_validation_table.py"
                  % os.path.relpath(OUT, ROOT))
            return 1
        print("validation table: current")
        return 0
    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write(text)
    print("wrote %s" % os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

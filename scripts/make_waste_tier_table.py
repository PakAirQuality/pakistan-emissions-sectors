"""Generate the waste tier-status appendix (S2), asserting every value it quotes.

The tier rows are authored HERE - tier status is reporting metadata, not a computed
result - but every parameter value a row quotes is asserted against data/
waste_params.csv at generation time, so a parameter edit that invalidates a tier claim
fails the build instead of shipping a stale table. A test asserts the committed .tex
matches a fresh regeneration.

The table refuses one word for the whole sector: the three categories carry different
levels of country-specific characterisation, the air layer is not on the IPCC tier
ladder at all, and the provincial allocation is an allocation, not a tier.

Usage:  python3 scripts/make_waste_tier_table.py
"""

from pkinv.assets import asset_path
import csv
import os
from pkinv.core.io import read_rows

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PARAMS = asset_path(ROOT, "data", "waste_params.csv")
OUT = asset_path(ROOT, "papers", "waste", "sections", "S2_tiers.tex")


def _params():
    return {r["param"]: float(r["value"]) for r in read_rows(PARAMS, comments=False)}


def rows():
    p = _params()
    # Every quoted value asserted against the engine's parameter file.
    assert p["gen_rate_urban"] == 0.453 and p["gen_rate_rural"] == 0.283
    assert p["uncollected_urban"] == 0.30 and p["uncollected_rural"] == 0.70
    assert p["burned_fraction"] == 0.60
    assert p["swds_mcf"] == 0.6 and p["swds_k"] == 0.065
    assert p["ww_mcf_sewer"] == 0.5 and p["ww_mcf_sewer_river"] == 0.1
    assert p["ww_bod_g_per_cap_day"] == 40
    effluent = next(r for r in read_rows(PARAMS, comments=False)
                    if r["param"] == "ww_ef_effluent")
    assert round(float(effluent["upper"]) / float(effluent["lower"])) == 150
    assert p["ww_n2o_method_2019"] == 1
    return [
        ("4A First Order Decay", "Tier 1, country-specific activity",
         "IPCC Vol 5 Ch 3 FOD with default $k$ (0.065), DOC$_f$, $F$ and the "
         "uncategorised-site MCF (0.6) over a district census population panel and "
         "Pakistani generation rates (0.453 / 0.283 kg/cap/day, Pak-EPA 1996). The "
         "activity is country-specific; every decay parameter is a default, and the "
         "MCF stands in for a site-type census Pakistan has never published."),
        ("4C2 Open burning", "Tier 1, country-specific activity",
         "IPCC Eq 5.7 over the uncollected stream (0.30 urban / 0.70 rural, What a "
         "Waste) $\\times$ the Box 5.1 burned fraction (0.60), with the Pak-EPA "
         "composition supplying carbon and dry matter. The burned fraction has no "
         "Pakistani measurement behind it."),
        ("4C2 air-pollutant layer", "Field factors (not an IPCC tier)",
         "Andreae 2019 garbage-burning factors on the identical burned mass. The IPCC "
         "tier ladder classifies greenhouse-gas estimation; a field-measurement factor "
         "set for co-emitted pollutants sits beside it, not on it."),
        ("4D1 CH$_4$", "Tier 1, stratified activity",
         "IPCC Vol 5 Ch 6 defaults (BOD 40 g/cap/day regional, $B_0$ 0.6) over the "
         "same population panel stratified by the JMP sanitation split - the "
         "stratification is country-specific, the factors are defaults, and the sewer "
         "MCF (0.5 central, 0.1 published alongside) is the sector's deciding "
         "judgement."),
        ("4D1 N$_2$O", "Tier 1",
         "FAOSTAT protein through the 2019 Refinement's nitrogen chain; the effluent "
         "factor's published range spans a factor of 150, the softest number in the "
         "sector."),
        ("Provincial allocation", "Country-specific allocation (not a tier)",
         "Three distinct district-population-derived proxies (burning, disposal, "
         "wastewater load), reconciling exactly to each category's national figure. "
         "IPCC tiers classify estimation, not allocation."),
    ]


def render():
    lines = [
        "% GENERATED by scripts/make_waste_tier_table.py - do not hand-edit;",
        "% a test asserts this file matches a fresh regeneration, and the generator",
        "% asserts every parameter value it quotes against data/waste_params.csv.",
        "% " + "=" * 75,
        "\\section{Supplementary Table: tier status by component}",
        "\\label{app:tiers}",
        "% " + "=" * 75,
        "",
        "Tier status differs by component. The three categories share one activity",
        "basis -- the district population panel -- but carry different levels of",
        "country-specific characterisation, and two pieces of the sector are not on",
        "the IPCC tier ladder at all. One word for the whole sector would either",
        "overstate the factors or understate the activity.",
        "",
        "\\begin{table*}[htbp]",
        "\\centering",
        "\\scriptsize",
        "\\begin{tabular}{@{}llp{0.55\\linewidth}@{}}",
        "\\toprule",
        "\\textbf{Component} & \\textbf{Status} & \\textbf{Basis} \\\\",
        "\\midrule",
    ]
    for comp, status, basis in rows():
        lines.append("%s & %s & %s \\\\[2pt]" % (comp, status, basis))
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\caption{Tier status by component. Generated; the parameter values quoted",
        "are asserted against \\texttt{data/waste\\_params.csv} at generation time.}",
        "\\label{tab:tierstatus}",
        "\\end{table*}",
        "",
    ]
    return "\n".join(lines)


def main():
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(render())
    print("wrote %s (%d rows)" % (OUT, len(rows())))


if __name__ == "__main__":
    main()

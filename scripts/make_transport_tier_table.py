"""Generate the transport tier-status appendix (S4), asserting every value it quotes.

The tier rows are authored HERE - tier status is reporting metadata, not a computed
result - but every factor value a row quotes is asserted against data/
emission_factors.csv at generation time, so a factor edit that invalidates a tier
claim fails the build instead of shipping a stale table. A test asserts the committed
.tex matches a fresh regeneration.

The table refuses the manuscript's old shorthand of one tier for the whole sector:
tier status differs by component, and the class split is a country-specific activity
allocation, not an IPCC tier at all.

Usage:  python3 scripts/make_transport_tier_table.py
"""

from pkinv.assets import asset_path
import csv
import os
from pkinv.core.io import read_rows

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EF = asset_path(ROOT, "data", "emission_factors.csv")
OUT = asset_path(ROOT, "papers", "transport", "sections", "S4_tiers.tex")


def _ef():
    return {(r["category"], r["item"]): float(r["value"]) for r in read_rows(EF, comments=False) if r["value"]}


def rows():
    ef = _ef()
    # Every quoted value asserted against the engine's factor file.
    assert ef[("transport_fuel_co2", "Motor Gasoline")] == 69300.0
    assert ef[("transport_fuel_co2", "Gas/Diesel Oil")] == 74100.0
    assert ef[("transport_fuel_n2o", "Gas/Diesel Oil")] == 3.9
    assert ef[("offroad_machinery_n2o", "Gas/Diesel Oil")] == 28.6
    assert ef[("offroad_machinery_co2", "Gas/Diesel Oil")] == ef[
        ("transport_fuel_co2", "Gas/Diesel Oil")]
    return [
        ("Road CO$_2$ (petrol, diesel)", "Tier 1, fuel-based",
         "OCAC Road customer-class rows $\\times$ IPCC Table 3.2.1 defaults (69,300 / 74,100 "
         "kg/TJ). The activity is country-specific and the anchor is exact by test; "
         "the factors are defaults, so Tier 1 despite the country-specific control."),
        ("Road CH$_4$, N$_2$O", "Tier 1",
         "Table 3.2.2 uncontrolled defaults on the same fuel energy. Tier 2 needs "
         "the technology distribution (emission-control classes) this fleet model "
         "does not resolve."),
        ("CNG stream", "Tier 1, metered activity",
         "OGRA metered sector gas $\\times$ Table 3.2.2 CNG defaults; the heating "
         "value is the declared assumption (900--1,000 Btu/scf), priced as a "
         "structural scenario."),
        ("Class split", "Country-specific allocation (not a tier)",
         "Registration-derived survival-weighted vehicle-km shares. IPCC tiers "
         "classify emission estimation, not allocation; calling the sector Tier 2 "
         "on the strength of this split would overstate it. No independent "
         "validation exists for the split (see the main paper's limitations)."),
        ("Mixed off-road (1A4c/1A2)", "Tier 1",
         "Diesel share by vehicle-km partition $\\times$ Table 3.3.1 defaults "
         "(N$_2$O 28.6 kg/TJ vs the road table's 3.9; the choice is pinned by "
         "test). The class absorbs the source workbook's residual bucket, so its "
         "composition is soft - though factor-invariant under Table 3.3.1, whose "
         "Agriculture and Industry diesel rows are identical."),
        ("Air-pollutant layer", "EMEP/EEA 2023 Tier 1",
         "Per class and process on the OCAC road fuel: exhaust in g/kg fuel (hot and "
         "cold running inside the factor, for an EU-27 2010 fleet), petrol evaporation, "
         "tyre and brake wear and road-surface wear. SO$_2$ from declared fuel sulfur by "
         "year. Resuspended road dust is not estimated; no Pakistan-specific cold-start "
         "or fleet-technology treatment is applied."),
        ("Spatial allocation", "Country-specific proxies (not a tier)",
         "Petroleum streams ride provincial fuel sales from OCAC's monthly area "
         "editions (petrol and diesel separately); CNG rides its own fleet "
         "vehicle-kilometre proxy and the mixed off-road class rides cropland. "
         "Reconciliation to the national control is exact by construction; the "
         "superseded registration proxy is retained as a published failure "
         "diagnostic."),
    ]


def render():
    lines = [
        "% GENERATED by scripts/make_transport_tier_table.py - do not hand-edit;",
        "% a test asserts this file matches a fresh regeneration, and the generator",
        "% asserts every factor value it quotes against data/emission_factors.csv.",
        "% " + "=" * 75,
        "\\section{Tier Status by Component}",
        "\\label{app:tiers}",
        "% " + "=" * 75,
        "",
        "Tier status differs by component, and two of the sector's defining pieces",
        "-- the class split and the spatial allocation -- are country-specific",
        "allocations that IPCC's tier ladder does not classify at all. One word for",
        "the whole sector would either overstate the factors or understate the",
        "activity.",
        "",
        "\\begin{table}[!htbp]",
        "\\centering",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{@{}>{\\raggedright\\arraybackslash}p{0.17\\linewidth}>{\\raggedright\\arraybackslash}p{0.18\\linewidth}>{\\raggedright\\arraybackslash}p{0.55\\linewidth}@{}}",
        "\\toprule",
        "\\textbf{Component} & \\textbf{Status} & \\textbf{Basis} \\\\",
        "\\midrule",
    ]
    for comp, status, basis in rows():
        lines.append("%s & %s & %s \\\\[2pt]" % (comp, status, basis))
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\caption{Tier status by component. Generated; the factor values quoted are",
        "asserted against \\texttt{data/emission\\_factors.csv} at generation time.}",
        "\\label{tab:tierstatus}",
        "\\end{table}",
        "",
    ]
    return "\n".join(lines)


def main():
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(render())
    print("wrote %s (%d rows)" % (OUT, len(rows())))


if __name__ == "__main__":
    main()

"""Write the release-provenance block that every technical report carries.

WHY. The nine sector papers are the maintained technical specification of a release, and
until now a printed copy said nothing about WHICH release. A reader holding
`railways_paper.pdf` could not tell whether it described the same run as the national
manuscript beside it, and in fact for two rounds it did not: the transport and waste papers
shipped pre-harmonisation figures, and nothing on the page would have told anyone.

So each report opens with a generated block naming the release version, the commit, the
reporting period, the baseline configuration, the two national totals and the SHA-256 of the
source manifest. It is written from `outputs/release_manifest.json` and regenerated with
everything else, so it cannot describe a release the numbers do not come from.

The block is one file, `paper_common/release_cover.tex`, which every report inputs. There is
deliberately no per-paper variant: nine copies of a provenance block is nine things to fall
out of step, which is the failure this exists to prevent.

Usage:  python3 scripts/make_release_cover.py [--check]
"""
import hashlib
import json
import os
import sys

sys.path.insert(0, os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src"))

from pkinv.assets import asset_path
from pkinv import release                                   # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = asset_path(ROOT, "outputs", "release_manifest.json")
OUT = asset_path(ROOT, "paper_common", "release_cover.tex")


def _tex(text):
    """LaTeX-safe: these strings come from a JSON manifest, not from a manuscript."""
    for char, esc in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"),
                      ("$", r"\$"), ("#", r"\#"), ("_", r"\_"), ("{", r"\{"),
                      ("}", r"\}"), ("~", r"\textasciitilde{}"),
                      ("^", r"\textasciicircum{}")):
        text = text.replace(char, esc)
    return text


SOURCE_MANIFEST = asset_path(ROOT, "data", "manifests", "source_manifest.csv")


def _sha256(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def manifest_digest():
    """SHA-256 of the release manifest itself, so a reader can check the page against
    the file."""
    return _sha256(MANIFEST)


def source_manifest_digest():
    """SHA-256 of data/manifests/source_manifest.csv - the source-acquisition register.

    rc9-rc40 printed the RELEASE manifest's digest under the label "Source manifest" (the
    nineteenth review's M-7): one digest, one wrong label, on fifteen PDFs. The two are
    different files with different lifetimes - the release manifest changes with every
    commit, the source register only when a document is acquired - and the cover now
    prints both under their own names."""
    return _sha256(SOURCE_MANIFEST)


def render():
    with open(MANIFEST, encoding="utf-8") as f:
        m = json.load(f)
    commit = m["git"]["describes_commit"] or "uncommitted"
    dirty = m["git"]["tree_dirty"]
    period = m["reporting_period"]
    totals = m["national_totals"]
    lines = [
        "%% GENERATED by scripts/make_release_cover.py from outputs/release_manifest.json.",
        "%% Do not edit: the edit will be overwritten and CI diffs the result.",
        r"\newcommand{\ReleaseCover}{%",
        # The box must fit INSIDE the column: \fbox adds 2\fboxrule + 2\fboxsep on top of the
        # minipage, so a 0.94\linewidth minipage overran every two-column sector paper by
        # 17.3pt - the same overrun, nine times, from one generated file. Subtracting the
        # frame explicitly is what makes it fit in any column width.
        r"\begin{center}\small",
        r"\setlength{\fboxsep}{4pt}%",
        r"\fbox{\begin{minipage}{\dimexpr\linewidth-2\fboxsep-2\fboxrule\relax}\footnotesize",
        r"\textbf{Release provenance.} This report documents one release of %s "
        r"and is generated against it. Where a sector report and the release's generated "
        r"product catalogue (\texttt{outputs/pakemis\_product\_catalog.csv}) disagree, "
        r"the catalogue is authoritative: sector reports are revised on their own cadence "
        r"and may lag the products.\\[2pt]" % release.PRODUCT,
        # The value column WRAPS. Fixed-width `l` made the tabular wider than the box in a
        # two-column layout - "448.00 Mt CO2e (AR5) under L; 442.88 Mt under S" does not fit a
        # 3.4-inch column - so the frame fitted and its contents did not.
        r"\begin{tabular}{@{}l@{\hspace{1em}}p{0.62\linewidth}@{}}",
        r"Release version & \texttt{%s} \\" % _tex(m["version"]),
        r"Commit & \texttt{%s}%s \\" % (_tex(commit[:12]),
                                        " (working tree modified)" if dirty else ""),
        r"Reporting period & %s (%s to %s)%s \\"
        % (_tex(period["label"]), _tex(period["start"]), _tex(period["end"]),
           "" if period["harmonised"] else ", not harmonised"),
        # The full description is a sentence and overflows the box; the code and basis are
        # what a reader needs to know which of the two national results this report is.
        r"Baseline configuration & %s (%s basis) \\"
        % (_tex(m["baseline_configuration"]["code"].split(":")[0]),
           _tex(m["baseline_configuration"]["basis"])),
        # the reference first, each under its own letter: S (survey dung) since rc67
        r"National total & %.2f Mt \COe{} (AR5) under S, the reference; %.2f Mt under L \\"
        % (totals["S"]["co2e_Mt_AR5"], totals["L"]["co2e_Mt_AR5"]),
        r"Release manifest & \texttt{%s} (SHA-256 of "
        r"\texttt{outputs/release\_manifest.json}, first 16) \\" % manifest_digest()[:16],
        r"Source manifest & \texttt{%s} (SHA-256 of "
        r"\texttt{data/manifests/source\_manifest.csv}, first 16) \\"
        % source_manifest_digest()[:16],
        r"Data-description article & \texttt{paper\_national/} (ESSD, in preparation), same release",
        r"\end{tabular}",
        r"\end{minipage}}",
        r"\end{center}}",
    ]
    return "\n".join(lines) + "\n"


# The commit and the RELEASE-manifest digest are ENVIRONMENTAL: CI regenerates the manifest,
# which stamps CI's HEAD into it, and every commit changes what "the current commit" is. A
# byte check would therefore fail on every push while nothing about the release had changed.
# The same reasoning is why the manifest's own regeneration test drops its git block.
# Everything else in the block - version, period, configuration, totals, and the SOURCE
# manifest digest, which is a property of the acquisition register - is a property of the
# release and IS compared.
VOLATILE = ("Commit &", "Release manifest &")


def _stable(text):
    return "\n".join(line for line in text.split("\n")
                      if not line.startswith(VOLATILE))


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    text = render()
    if "--check" in argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if _stable(current) != _stable(text):
            print("paper_common/release_cover.tex is stale; run "
                  "python3 scripts/make_release_cover.py")
            return 1
        print("release cover block is current.")
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("release cover written to %s" % os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())

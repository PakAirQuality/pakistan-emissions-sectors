"""Generate the source x pollutant air completeness matrix (S4) from the engine.

The GHG side has a completeness matrix (S3); the reviewer's requirement is the air
side's equivalent: every stream x pollutant combination marked E, NE, NO or IE, with E
cells DERIVED by introspecting the air layer's actual rows (so the matrix cannot claim
coverage the engine does not compute) and every NE cell carrying a declared reason from
the registry below. Same generate-and-sync discipline as S2/S3.

Usage:  python3 scripts/make_residential_air_matrix.py
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))

from pkinv.assets import asset_path
OUT = asset_path(ROOT, "papers", "residential", "sections", "S4_air_matrix.tex")

POLLUTANTS = ["PM2.5", "PM10", "TSP", "BC", "OC", "CO", "NOx", "NMVOC", "SO2", "NH3"]
STREAMS = ["Natural gas", "LPG", "Kerosene", "Coal", "Generators", "Dung cake",
           "Firewood", "Charcoal", "Crop residues", "Biogas"]

# (stream, pollutant) -> NE reason, for every cell the engine does not compute.
# Reasons reference where the omission is declared; a cell in neither the engine nor
# this registry fails the generation loudly.
NE_REASONS = {
    ("Generators", "*"): "no household-genset factor class exists in the held EMEP "
                         "chapter; declared omission bounded by the stream's 56 kt of "
                         "fuel (the non-road small-engine chapter is the registered "
                         "upgrade)",
    ("Charcoal", "SO2"): "the source cell prints a range its own average falls "
                         "outside, on two measurements - unusable, omitted rather "
                         "than guessed",
    ("Natural gas", "NH3"): "not applicable in the chapter's gaseous-fuel table; "
                            "omitted, never zero-filled",
    ("LPG", "NH3"): "not applicable in the chapter's gaseous-fuel table",
    ("Kerosene", "NH3"): "not applicable in the chapter's liquid-fuel table",
    ("*", "PM10"): "Andreae tabulates TPM, not PM10; the coarse fraction is not "
                   "adopted for biomass and the gaseous/liquid chapters' PM10 adds "
                   "nothing above PM2.5 for premixed flames",
    ("*", "TSP"): "as PM10: not adopted for biomass; the coal row is the one solid "
                  "fuel with a chapter TSP factor",
    ("*", "OC"): "no OC factor adopted for this stream",
    ("*", "BC"): "no BC factor or fraction adopted for this stream",
    ("Biogas", "*"): "the stream itself is NE (no digester count exists; see the "
                     "completeness matrix and residential-biogas in the gap register)",
}


def engine_cells():
    from pkinv.sectors.residential import air_pollutants
    from pkinv.sectors.residential.data import ResidentialData
    cells = set()
    for r in air_pollutants.compute(ResidentialData()):
        stream = r["subitem"].rsplit(" ", 1)[0]
        cells.add((stream, r["pollutant"]))
    return cells


def _reason(stream, poll):
    for key in ((stream, poll), (stream, "*"), ("*", poll)):
        if key in NE_REASONS:
            return NE_REASONS[key]
    raise SystemExit("no NE reason registered for (%s, %s) - either the engine "
                     "should compute it or the registry must explain why not"
                     % (stream, poll))


def render():
    cells = engine_cells()
    lines = [
        "% GENERATED by scripts/make_residential_air_matrix.py - do not hand-edit;",
        "% a test regenerates this file and asserts the committed copy matches.",
        "% " + "=" * 75,
        "\\section{Supplementary Table: the air-pollutant completeness matrix}",
        "\\label{app:airmatrix}",
        "% " + "=" * 75,
        "",
        "Every stream--pollutant combination, E derived from the air layer's actual",
        "rows (the matrix cannot claim coverage the engine does not compute) and every",
        "NE carrying its declared reason, keyed below the table. All estimated cells",
        "are gross emitted mass at the appliance, on the reference (household-survey) quantity for the dung row.",
        "",
        "\\begin{table*}[htbp]",
        "\\centering",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabular}{@{}l" + "c" * len(POLLUTANTS) + "@{}}",
        "\\toprule",
        "\\textbf{Stream} & " + " & ".join(
            {"PM2.5": "PM$_{2.5}$", "PM10": "PM$_{10}$",
             "NOx": "NO$_x$$^{n}$", "SO2": "SO$_2$", "NH3": "NH$_3$"}.get(p, p)
            for p in POLLUTANTS) + " \\\\",
        "\\midrule",
    ]
    notes = {}
    for stream in STREAMS:
        row = [stream]
        for poll in POLLUTANTS:
            if (stream, poll) in cells:
                row.append("E")
            else:
                reason = _reason(stream, poll)
                mark = notes.setdefault(reason, chr(ord("a") + len(notes)))
                row.append("NE$^{%s}$" % mark)
        lines.append(" & ".join(row) + " \\\\")
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\caption{The air-pollutant completeness matrix. $^{n}$NO$_2$-equivalent",
        "basis throughout. NE reasons:",
    ]
    for reason, mark in sorted(notes.items(), key=lambda kv: kv[1]):
        lines.append("$^{%s}$~%s." % (mark, reason))
    lines += [
        "}",
        "\\label{tab:airmatrix}",
        "\\end{table*}",
        "",
    ]
    return "\n".join(lines)


def main():
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(render())
    print("wrote %s" % OUT)


if __name__ == "__main__":
    main()

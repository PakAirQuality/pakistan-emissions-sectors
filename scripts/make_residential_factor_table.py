"""Generate the residential air-pollutant factor appendix (S2) from the factor file.

One source of truth: every factor the air layer can burn is a row in
data/emission_factors.csv, and this script renders those rows into
papers/residential/sections/S2_factors.tex. The table is GENERATED, never hand-edited -
tests/test_residential_crt.py (TestFactorAppendix) regenerates it in memory and asserts
the committed file matches, so a factor change that skips the regeneration step fails
loudly instead of leaving the paper citing a value the engine no longer uses.

Usage:  python3 scripts/make_residential_factor_table.py
"""

from pkinv.assets import asset_path
import csv
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EF = asset_path(ROOT, "data", "emission_factors.csv")
OUT = asset_path(ROOT, "papers", "residential", "sections", "S2_factors.tex")

POLL_NAME = {"PM25": "PM$_{2.5}$", "PM10": "PM$_{10}$", "TSP": "TSP", "BC": "BC",
             "OC": "OC", "CO": "CO", "NOx": "NO$_x$", "NMVOC": "NMVOC",
             "SO2": "SO$_2$", "NH3": "NH$_3$"}
FUEL_NAME = {"Wood": "Firewood", "Dung": "Dung cake", "Residue": "Crop residues",
             "Charcoal": "Charcoal", "NaturalGas": "Natural gas", "LPG": "LPG",
             "Kerosene": "Kerosene", "Coal": "Coal"}
# source string -> compact citation-ish label
SOURCE_SHORT = (("Andreae 2019", "Andreae 2019"),
                ("Akagi", "Akagi 2011"),
                ("EMEP/EEA Air Pollutant", "EMEP/EEA 2023 ch.\\,1.A.4"),
                ("EMEP/EEA 2019", "EMEP/EEA 2019 (mirror)"),
                ("IPCC 2006 V4", "IPCC 2006 V4 (mirror)"),
                ("Zhang", "Zhang et al. 2012"))


def _short_source(src):
    for needle, label in SOURCE_SHORT:
        if needle in src:
            return label
    return src[:24]


def _flags(row):
    note = (row["note"] or "") + (row["source"] or "")
    f = []
    if "filterable" in note.lower():
        f.append("c")           # filterable/condensable caveat quoted on the row
    if "+/-100" in note or "defective" in note.lower() or "does not bracket" in note.lower() \
            or "upper bound is" in note:
        f.append("d")           # defective printed CI, carried at +/-100
    if "sulfur" in note.lower() or "S of coal" in note or "1.2 % S" in note:
        f.append("s")           # sulfur-content assumption stated on the row
    return ",".join(f)


def rows():
    with open(EF, newline="", encoding="utf-8") as fh:
        all_rows = list(csv.DictReader(fh))
    out = []
    for r in all_rows:
        if r["category"] == "residential_biofuel":
            _g, poll, fuel = r["item"].split("_")
            out.append((POLL_NAME[poll], FUEL_NAME[fuel], r["value"],
                        "g/kg dry", _short_source(r["source"]), _flags(r),
                        r["uncert_pct"]))
        elif r["category"] == "residential_air_fossil":
            _g, poll, fuel = r["item"].split("_")
            out.append((POLL_NAME[poll], FUEL_NAME[fuel], r["value"],
                        "g/GJ", _short_source(r["source"]), _flags(r),
                        r["uncert_pct"]))
        elif r["category"] == "residential_air_fossil_frac":
            cls = r["item"].split("_")[-1]
            out.append(("BC", "%s fuels" % cls.capitalize(), r["value"],
                        "frac.\\ of PM$_{2.5}$", _short_source(r["source"]),
                        _flags(r), r["uncert_pct"]))
    order = {p: i for i, p in enumerate(
        ["PM$_{2.5}$", "PM$_{10}$", "TSP", "BC", "OC", "CO", "NO$_x$", "NMVOC",
         "SO$_2$", "NH$_3$"])}
    out.sort(key=lambda t: (order.get(t[0], 99), t[1]))
    return out


def render():
    lines = [
        "% GENERATED by scripts/make_residential_factor_table.py - do not hand-edit;",
        "% tests/test_residential_crt.py asserts this file matches the factor data.",
        "% " + "=" * 75,
        "\\section{Supplementary Table: every air-pollutant factor the layer burns}",
        "\\label{app:factors}",
        "% " + "=" * 75,
        "",
        "Basis rules, stated once: biomass factors are per kilogram of dry fuel",
        "including ash (total dry solids for dung, oven-dry for firewood, dry matter",
        "for residues, as-purchased for charcoal); fossil factors are per gigajoule of",
        "fuel energy; black carbon is reported INSIDE PM$_{2.5}$, never additional to",
        "it; NO$_x$ is reported as NO$_2$-equivalent throughout---sources publishing",
        "as~NO (the Andreae rows) are converted $\\times 46/30$ on their data rows, so",
        "one basis sums; the device is a single implicit class per fuel---the",
        "traditional/open class that dominates rural biomass cooking (71.8\\% of rural",
        "households per the MTF 2021--22 stove typology; the fuel-by-device crosswalk",
        "needed for full technology resolution is not yet published). All",
        "values are gross emission at the appliance. Flags: c~=~the source's own",
        "filterable-versus-condensable caveat is quoted on the data row; d~=~the",
        "printed confidence interval is defective and the row carries $\\pm$100 with",
        "the bounds quoted; s~=~a sulfur-content assumption is stated on the row.",
        "",
        "\\begin{table*}[htbp]",
        "\\centering",
        "\\scriptsize",
        "\\begin{tabular}{@{}llrlllr@{}}",
        "\\toprule",
        "\\textbf{Pollutant} & \\textbf{Fuel} & \\textbf{Value} & \\textbf{Unit} & "
        "\\textbf{Source} & \\textbf{Flags} & \\textbf{$\\pm$\\%} \\\\",
        "\\midrule",
    ]
    for poll, fuel, val, unit, src, flags, u in rows():
        lines.append("%s & %s & %s & %s & %s & %s & %s \\\\"
                     % (poll, fuel, val, unit, src, flags or "--", u))
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\caption{The complete air-pollutant factor set, generated from the factor",
        "file the engine reads (\\texttt{data/emission\\_factors.csv}). Omissions are",
        "deliberate and declared in the text: charcoal SO$_2$ (unusable source cell),",
        "NH$_3$ for gaseous and liquid fuels (not applicable in the chapter's tables),",
        "and every generator pollutant (no household-genset factor class exists).}",
        "\\label{tab:factors}",
        "\\end{table*}",
        "",
    ]
    return "\n".join(lines)


def main():
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(render())
    print("wrote %s (%d factor rows)" % (OUT, len(rows())))


if __name__ == "__main__":
    main()

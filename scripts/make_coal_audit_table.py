#!/usr/bin/env python3
"""The coal supply bound's five rescue routes, as a table generated from the audit product.

WHY. The article said "None rescues it." That sentence is an interpretation; the evidence is
five numbered tests with numerical rescue requirements in
outputs/pakemis_power_reference_audit.csv (B1..B6). A table generated from that product lets a
reader see each bound; prose that weighs them is the author's to write (author_actions AA-010).

Usage:  python3 scripts/make_coal_audit_table.py [--check]
Writes: paper_national/versions/v3/generated/tab_coal_audit.tex
"""
import csv, io, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "outputs", "pakemis_power_reference_audit.csv")
OUT = os.path.join(ROOT, "paper_national", "versions", "v3", "generated", "tab_coal_audit.tex")
LABEL = {"B1_the_bound": "B1 Tonnage required against supply", "B2_matched_period": "B2 Supply covers the same twelve months",
         "B3_stock_change": "B3 Inventory drawdown could supply the gap", "B4_coal_rank": "B4 Assumed lignite share",
         "B5_calorific_value": "B5 Fleet calorific value", "B6_fleet_coverage": "B6 Fleet coverage of the station account"}
def esc(s): return s.replace("\\", "\\textbackslash{}").replace("%", "\\%").replace("_", "\\_").replace("&", "\\&").replace("#", "\\#").replace("$", "\\$")
def build():
    body = "".join(l for l in io.open(SRC, encoding="utf-8") if not l.startswith("#"))
    rows = [r for r in csv.DictReader(io.StringIO(body)) if r["test_id"] in LABEL]
    rows.sort(key=lambda r: r["test_id"])
    L = ["%% GENERATED by scripts/make_coal_audit_table.py from outputs/pakemis_power_reference_audit.csv. Do not edit.",
         "\\begin{table*}[t]",
         "\\caption{The FY2023--24 coal supply bound and its five rescue routes, from the power reference audit. Each row states the test, its value, the audit's verdict and the change in the records that would be required to reverse it. The supply basis is imports plus production (Finance Division Statistical Supplement Table 14.3); it carries no stock term.}",
         "\\label{tab:coal_audit}", "\\footnotesize",
         "\\begin{tabular}{@{}>{\\raggedright\\arraybackslash}p{3.4cm}>{\\raggedright\\arraybackslash}p{2.9cm}>{\\raggedright\\arraybackslash}p{4.0cm}>{\\raggedright\\arraybackslash}p{6.1cm}@{}}", "\\tophline",
         "Test & Value & Verdict & What would reverse it \\\\", "\\middlehline"]
    for r in rows:
        val = (r["value"] + " " + r["unit"]).strip()
        L.append("%s & %s & %s & %s \\\\" % (esc(LABEL[r["test_id"]]), esc(val), esc(r["verdict"]), esc(r["rescue_requirement"])))
    L += ["\\bottomhline", "\\end{tabular}", "\\end{table*}", ""]
    return "\n".join(L)
def main(argv):
    fresh = build()
    if "--check" in argv:
        held = io.open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        print("coal audit table: %s" % ("byte-identical" if held == fresh else "DIFFERS")); return 0 if held == fresh else 1
    io.open(OUT, "w", encoding="utf-8").write(fresh); print("wrote", os.path.relpath(OUT, ROOT)); return 0
if __name__ == "__main__": sys.exit(main(sys.argv[1:]))

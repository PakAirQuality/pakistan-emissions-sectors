#!/usr/bin/env python3
"""Check that this public repository tracks nothing it may not publish, and write its ODbL notice.

WHY THIS EXISTS. Through rc68 the public repository was a COPY of each release, made by
scripts/make_public_copy.py from a private repository that held everything. From rc69 the
work is committed here directly, and the third-party documents, rasters and working notes stay
in the private checkout, mounted beside a clone as the restricted layers
(src/pkinv/core/layers.py, scripts/overlay.py). The copier's list of what to leave out became
that module's list of what is restricted, and the copier became this check: a rule that
decides what is PUBLISHED fails in one direction only, so it runs before every push
(make public-check, the public CI) rather than once per release.

It fails when:
  - a tracked path is restricted (a document, a raster, survey microdata, working notes);
  - a tracked file exceeds GitHub's limit (this project's own large products ship in the
    deposit; they are ignored here);
  - a restricted name is not ignored, so a mount could be committed by `git add -A`;
  - NOTICE-ODbL.md does not list exactly the tracked files that carry ODbL obligations.

Usage:  python3 scripts/check_public_tree.py            check
        python3 scripts/check_public_tree.py --write    rewrite NOTICE-ODbL.md, then check
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))

from pkinv.core import layers  # noqa: E402

NOTICE = "NOTICE-ODbL.md"


def tracked():
    out = subprocess.check_output(["git", "-C", ROOT, "ls-files", "-z"]).decode()
    return [p for p in out.split("\0") if p]


def restricted_tracked(paths):
    return [(p, layers.restricted_reason(p)) for p in paths if layers.is_restricted(p)]


def too_large(paths):
    found = []
    for path in paths:
        full = os.path.join(ROOT, path)
        if (os.path.isfile(full) and not os.path.islink(full)
                and os.path.getsize(full) > layers.SIZE_LIMIT_BYTES):
            found.append(path)
    return found


def not_ignored():
    """Restricted names a `git add -A` would pick up if they were mounted here."""
    names = [p for p, _ in layers.RESTRICTED_TREES] + [p for p, _ in layers.RESTRICTED_FILES]
    names += [pattern.replace("*", "example") for pattern, _ in layers.RESTRICTED_PATTERNS]
    names += ["data/sectors/x/survey" + suffix for suffix in layers.FORBIDDEN_SUFFIXES]
    names += list(layers.TOO_LARGE) + [layers.CONFIG]
    missing = []
    for name in names:
        run = subprocess.run(["git", "-C", ROOT, "check-ignore", "-q", "--no-index", name])
        if run.returncode != 0:
            missing.append(name)
    return missing


def odbl_paths(paths):
    """Tracked files the deposit packages in its ODbL companion, by the deposit's own rule."""
    from pkinv.report.deposit_licensing import upstream_dependencies
    from pkinv.report.deposit_manifest import source_documents
    by_data_file = {r["data_file"]: r for r in source_documents()}
    return sorted(p for p in paths if upstream_dependencies(p, by_data_file))


def notice(paths):
    lines = [
        "# Files in this repository that carry Open Database License obligations",
        "",
        "Most of this repository is this project's own work: code under the MIT licence",
        "(`LICENSE`), and data and text under CC BY 4.0 (`LICENSE-data`). The files listed",
        "below are different. They are derived from OpenStreetMap or from other databases",
        "under the Open Database License 1.0, or they are earlier releases and spatial",
        "products whose lineage was not cleared file by file, so they are treated the same",
        "way. They are distributed under the ODbL (`LICENSE-ODbL`), with its attribution and",
        "share-alike obligations, and the original contents licences still apply. The",
        "archive deposit packages the same files in its separate ODbL companion, by the same",
        "rule (`src/pkinv/report/deposit_licensing.py`).",
        "",
        "Attribution: © OpenStreetMap contributors, https://www.openstreetmap.org/copyright.",
        "",
        "This list is generated by `python3 scripts/check_public_tree.py --write`, and the",
        "public checks fail when it does not match the tracked tree. %d files:" % len(paths),
        "",
    ]
    lines += ["- `%s`" % p for p in paths]
    return "\n".join(lines) + "\n"


def main(argv):
    paths = tracked()
    expected = notice(odbl_paths(paths + ([NOTICE] if NOTICE not in paths else [])))
    if "--write" in argv:
        with open(os.path.join(ROOT, NOTICE), "w", encoding="utf-8") as handle:
            handle.write(expected)
    problems = []
    for path, reason in restricted_tracked(paths):
        problems.append("tracked but restricted (%s): %s" % (reason, path))
    for path in too_large(paths):
        problems.append("tracked and over GitHub's file limit: %s" % path)
    for name in not_ignored():
        problems.append("restricted name not ignored by .gitignore: %s" % name)
    try:
        with open(os.path.join(ROOT, NOTICE), encoding="utf-8") as handle:
            current = handle.read()
    except FileNotFoundError:
        current = None
    if current != expected:
        problems.append("%s does not list the tracked ODbL files; run "
                        "python3 scripts/check_public_tree.py --write" % NOTICE)
    print("public tree: %d tracked files, %d problems" % (len(paths), len(problems)))
    for problem in problems:
        print("  " + problem)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

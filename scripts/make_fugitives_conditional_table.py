"""Generate the fugitives supplement's conditional-interval table (S6).

WHY. The thirteenth review caught the hand-written table missing the central
member the paper itself describes (18.873 Mt, [16.544, 22.821]) and the
supplement still saying 168 configurations against the engine's 224 - the exact
drift class the generated-fragment discipline exists to kill. The table is now
rendered from the two products it restates, so a configuration cannot ship and
be absent from it.

Reads:  outputs/fugitives_conditional_intervals_2024.csv   (5 configurations)
        outputs/fugitives_distribution_shape_sensitivity_2024.csv (3 shapes)
Writes: papers/fugitives/sections/S6_conditional_table.tex

Usage:  python3 scripts/make_fugitives_conditional_table.py [--check]
"""

from pkinv.assets import asset_path
import csv
import os
import sys
from pkinv.core.io import read_rows

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = asset_path(ROOT, "papers", "fugitives", "sections",
                   "S6_conditional_table.tex")

LABELS = {
    "reference": "Reference",
    "central": "Central (geometric-mean practice)",
    "lower_practices": "Lower practices",
    "no_post_meter_industrial": "No industrial post-meter",
    "minimum_coverage_combined": "Minimum coverage",
}
ORDER = ("reference", "central", "lower_practices",
         "no_post_meter_industrial", "minimum_coverage_combined")
SHAPE_LABELS = {"bounded_uniform": "bounded uniform",
                "bounded_loguniform_positive": "bounded log-uniform$^a$"}


def _rows(name):
    path = asset_path(ROOT, "outputs", name)
    return read_rows(path)


def render():
    conditionals = {r["configuration"]: r
                    for r in _rows("fugitives_conditional_intervals_2024.csv")}
    missing = set(ORDER) - set(conditionals)
    extra = set(conditionals) - set(ORDER)
    if missing or extra:
        raise SystemExit("the conditional-interval product and this table's "
                         "configuration list disagree: missing %s, extra %s - "
                         "update ORDER deliberately" % (sorted(missing),
                                                        sorted(extra)))
    shapes = [r for r in _rows("fugitives_distribution_shape_sensitivity_2024.csv")
              if r["distribution"] in SHAPE_LABELS]

    lines = [
        "% GENERATED by scripts/make_fugitives_conditional_table.py - do not "
        "hand-edit; a test asserts this file matches a fresh regeneration.",
        "% The hand-written predecessor shipped without the central member the "
        "paper itself describes - the thirteenth review's finding.",
        r"\begin{table}[H]",
        r"\centering",
        r"\footnotesize",
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{@{}llrrrr@{}}",
        r"\toprule",
        r"\textbf{Experiment} & \textbf{Distribution} & \textbf{Deterministic} &",
        r"\textbf{P2.5} & \textbf{Median} & \textbf{P97.5} \\",
        r"\midrule",
    ]
    for key in ORDER:
        r = conditionals[key]
        lines.append("%s & split triangular & %.3f & %.3f & %.3f & %.3f \\\\" % (
            LABELS[key], float(r["deterministic_mt_co2e_ar5"]),
            float(r["mc_p025_mt_co2e_ar5"]), float(r["mc_p50_mt_co2e_ar5"]),
            float(r["mc_p975_mt_co2e_ar5"])))
    for r in shapes:
        lines.append("Reference shape test & %s & %.3f & %.3f & %.3f & %.3f \\\\"
                     % (SHAPE_LABELS[r["distribution"]],
                        float(conditionals["reference"]["deterministic_mt_co2e_ar5"]),
                        float(r["p025_mt_co2e_ar5"]), float(r["p50_mt_co2e_ar5"]),
                        float(r["p975_mt_co2e_ar5"])))
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"}",
        r"\caption{Conditional 95\% intervals for the five interpretable "
        r"configurations, and distribution-shape sensitivity, Mt CO$_2$e. The "
        r"central member is a synthesized geometric-mean reading, priced and "
        r"never selected.}",
        r"\label{tab:s6conditional}",
        r"\end{table}",
        r"\noindent\footnotesize $^a$Inputs with a zero lower bound use bounded "
        r"uniform sampling.\normalsize",
    ]
    return "\n".join(lines) + "\n"


def main():
    fresh = render()
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8") as f:
            if f.read() != fresh:
                raise SystemExit("S6_conditional_table.tex is stale; rerun "
                                 "scripts/make_fugitives_conditional_table.py")
        print("S6_conditional_table.tex matches a fresh render")
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(fresh)
    print("wrote %s" % os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

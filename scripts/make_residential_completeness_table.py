"""Generate the residential completeness matrix appendix (S3) from the engine's table.

Same discipline as S2: the paper's completeness matrix is rendered from
outputs/completeness.csv (itself generated by pkinv.report.completeness and synced to
the gap register by test), never hand-edited, and a test asserts the committed .tex
matches a fresh regeneration.

Usage:  python3 scripts/make_residential_completeness_table.py
"""

from pkinv.assets import asset_path
import csv
import os
import re
from pkinv.core.io import read_rows

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = asset_path(ROOT, "outputs", "completeness.csv")
OUT = asset_path(ROOT, "papers", "residential", "sections", "S3_completeness.tex")


def _tex(s, width=None):
    s = (s.replace("&", "\\&").replace("%", "\\%").replace("_", "\\_")
         .replace("#", "\\#"))
    if width and len(s) > width:
        s = s[:width - 1].rstrip() + "\\ldots"
    return s


def rows():
    return [r for r in read_rows(SRC, comments=False) if r["code"] == "1.A.4.b"]


def render():
    lines = [
        "% GENERATED by scripts/make_residential_completeness_table.py - do not",
        "% hand-edit; a test asserts this file matches the engine's completeness table.",
        "% " + "=" * 75,
        "\\section{Supplementary Table: the 1.A.4.b completeness matrix}",
        "\\label{app:completeness}",
        "% " + "=" * 75,
        "",
        "Every category--gas combination the sector might contain, with its IPCC",
        "notation key and the justification the engine carries for every non-E entry.",
        "Generated from the same completeness table the national inventory publishes,",
        "which is itself synced to the gap register by test.",
        "",
        "\\begin{table*}[htbp]",
        "\\centering",
        "\\scriptsize",
        "\\begin{tabular}{@{}lclp{0.52\\linewidth}@{}}",
        "\\toprule",
        "\\textbf{Category} & \\textbf{Key} & \\textbf{Gases} & "
        "\\textbf{Justification (abridged)} \\\\",
        "\\midrule",
    ]
    for r in rows():
        cat = _tex(r["category"].replace("Residential - ", ""))
        just = _tex(re.sub(r"\s+", " ", r["justification"]).strip(), 240)
        lines.append("%s & %s & %s & %s \\\\[2pt]"
                     % (cat, r["notation_key"], _tex(r["gas"]), just))
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\caption{The residential completeness matrix, generated from the engine",
        "(\\texttt{outputs/completeness.csv}, 1.A.4.b rows). Full justifications,",
        "including the magnitudes that bound each NE entry where a comparator exists,",
        "are in the generated national table.}",
        "\\label{tab:completeness144b}",
        "\\end{table*}",
        "",
    ]
    return "\n".join(lines)


def main():
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(render())
    print("wrote %s (%d rows)" % (OUT, len(rows())))


if __name__ == "__main__":
    main()

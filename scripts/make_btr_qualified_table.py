#!/usr/bin/env python3
"""The BTR subjects that are not ratios, as a table generated from the figure data.

Usage:  python3 scripts/make_btr_qualified_table.py [--check]
Writes: paper_national/versions/v3/generated/tab_btr_qualified.tex
"""
import csv, io, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "paper_national", "figures", "rewrite_inputs", "data", "btr_qualified_rows.csv")
OUT = os.path.join(ROOT, "paper_national", "versions", "v3", "generated", "tab_btr_qualified.tex")
TIER = {"aggregate-restated": "submission carries it only inside a wider aggregate",
        "scope-gap": "scope differs between the two accounts",
        "btr-only": "estimated only by the submission",
        "btr-zero": "reported as zero by the submission",
        "btr-elsewhere": "reported under another category by the submission",
        "out-of-scope": "outside this inventory's scope"}
def esc(s): return s.replace("%", "\\%").replace("_", "\\_").replace("&", "\\&").replace("CO2", "CO$_2$")
def build():
    rows = list(csv.DictReader(io.open(SRC, encoding="utf-8")))
    L = ["%% GENERATED by scripts/make_btr_qualified_table.py from btr_qualified_rows.csv. Do not edit.",
         "\\begin{table}[t]",
         "\\caption{Subjects of the comparison with Pakistan's First Biennial Transparency Report (inventory year 2020--21) that cannot be expressed as a ratio, with the mass each side reports in Mt CO$_2$e (AR5). A blank cell means the account does not estimate the subject.}",
         # THE TABLE WAS 19.8 pt WIDER THAN ITS COLUMN in the two-column layout: its rules crossed
         # the gutter and ran under the next column. Narrower text columns and column spacing bring
         # it inside 85 mm; the review layout, one column wide, never showed it.
         "\\label{tab:btr_qualified}", "\\footnotesize", "\\setlength{\\tabcolsep}{4pt}",
         "\\begin{tabular}{@{}>{\\raggedright\\arraybackslash}p{2.8cm}rr>{\\raggedright\\arraybackslash}p{2.9cm}@{}}", "\\tophline",
         "Subject & BTR & PakEmis & Why not a ratio \\\\", "\\middlehline"]
    for r in rows:
        L.append("%s & %s & %s & %s \\\\" % (esc(r["subject"]), r["btr_Mt_co2e"] or "--",
                                            r["pakemis_Mt_co2e"] or "--", TIER[r["tier"]]))
    L += ["\\bottomhline", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(L)
def main(argv):
    fresh = build()
    if "--check" in argv:
        held = io.open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        print("btr qualified table: %s" % ("byte-identical" if held == fresh else "DIFFERS")); return 0 if held == fresh else 1
    io.open(OUT, "w", encoding="utf-8").write(fresh); print("wrote", os.path.relpath(OUT, ROOT)); return 0
if __name__ == "__main__": sys.exit(main(sys.argv[1:]))

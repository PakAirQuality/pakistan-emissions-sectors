"""Write the availability statements the manuscripts carry, from the release manifest.

WHY. An ESSD data-description article must carry formal Data availability and Code
availability sections naming the dataset DOI, the software DOI and the licence terms, and
the abstract must cite the dataset DOI once it exists. Those identifiers are minted at
deposit, after the content is frozen, and typing them into three documents by hand is how
a manuscript ends up naming a placeholder or an old release. So the sentences that carry
them are GENERATED from `outputs/release_manifest.json` - the one place the identifiers
are recorded - and regenerated with everything else. An empty identifier prints an honest
"assigned on deposit" sentence, never a placeholder; a filled one prints the DOI and cites
the deposit's bibliography entry.

Writes, deterministically (no timestamps, no commit hash - the release cover carries those):

    paper_national/versions/<v>/generated/availability.tex      \\dataavailability{...} \\codeavailability{...}
    paper_national/versions/<v>/generated/abstract_doi.tex      one sentence appended to the abstract
    paper_common/generated_availability_tn.tex     one paragraph the sector technical notes input

The two Copernicus statements end by calling the manuscript's own \\pkinvDataTerms and
\\pkinvCodeTerms (guarded by \\ifdefined): the custody counts and the repository entry
points are manuscript prose whose numbers the claims registry checks, so they stay in
paper_national.tex rather than being re-typed here.

Usage:  python3 scripts/make_availability.py [--check] [--root DIR] [--out DIR]
        --root   repository root to read the manifest from (default: this checkout)
        --out    tree to write into (default: --root); the three paths above are relative to it
"""

from pkinv.assets import asset_path
from pkinv.paths import PAPER_NATIONAL_REPORT_REL  # noqa: E402
import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

MANIFEST = asset_path("outputs", "release_manifest.json")

AVAILABILITY = asset_path(PAPER_NATIONAL_REPORT_REL, "generated", "availability.tex")
ABSTRACT_DOI = asset_path(PAPER_NATIONAL_REPORT_REL, "generated", "abstract_doi.tex")
TN_PARAGRAPH = asset_path("paper_common", "generated_availability_tn.tex")

HEADER = ("%% GENERATED by scripts/make_availability.py from outputs/release_manifest.json.\n"
          "%% Do not edit: the edit will be overwritten and a test compares this file to a "
          "fresh render.\n")

# Bibliography keys of the three deposits (paper_common/references.bib). Cited only once
# the matching identifier is filled, so a build never cites a record that does not exist.
BIBKEYS = {"data": "pakemis2026data", "software": "pakemis2026software",
           "documentation": "pakemis2026documentation"}


def _tex(text):
    """LaTeX-safe: these strings come from a JSON manifest, not from a manuscript."""
    for char, esc in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"),
                      ("$", r"\$"), ("#", r"\#"), ("_", r"\_"), ("{", r"\{"),
                      ("}", r"\}"), ("~", r"\textasciitilde{}"),
                      ("^", r"\textasciicircum{}")):
        text = text.replace(char, esc)
    return text


def _doi_url(doi):
    return r"\url{https://doi.org/%s}" % doi


def _doi(manifest, kind):
    return (manifest.get("doi") or {}).get(kind, "") or ""


def _data_statement(m):
    version = _tex(m["version"])
    licences = m.get("licences", {})
    doi = _doi(m, "data")
    parts = []
    if doi:
        parts.append(r"The dataset described here is PakEmis %s, archived under %s "
                     r"\citep{%s}." % (version, _doi_url(doi), BIBKEYS["data"]))
    else:
        parts.append(r"The dataset described here is PakEmis %s. The dataset DOI is assigned "
                     r"on deposit; until then the release is identified by version and "
                     r"manifest digest (\texttt{outputs/release\_manifest.json}, whose SHA-256 "
                     r"the release cover of every technical note prints)." % version)
    doc_doi = _doi(m, "documentation")
    if doc_doi:
        parts.append(r"The technical documentation---the sector technical notes and this "
                     r"supplement---is deposited with the data under %s \citep{%s}."
                     % (_doi_url(doc_doi), BIBKEYS["documentation"]))
    else:
        parts.append(r"The technical documentation---the sector technical notes and this "
                     r"supplement---is included in the local release package. External "
                     r"review deposit and persistent identifiers are pending.")
    code = _tex(licences.get("code", ""))
    data = _tex(licences.get("data_and_text", ""))
    if code and data:
        parts.append(r"The code is licensed under %s. Project-owned primary products and "
                     r"text use CC~BY~4.0; third-party inputs retain their stated terms. "
                     r"OpenStreetMap-derived databases and affected legacy spatial products "
                     r"are separated into an ODbL~1.0 companion. The primary geographic "
                     r"products are rebuilt without OpenStreetMap geometry or weights. "
                     r"The package includes the product-specific licence audit." % code)
    undetermined = licences.get("undetermined", "")
    if undetermined:
        parts.append(r"One evaluation-only input carries no licence declaration in the "
                     r"record and is excluded from the primary data record until its rights "
                     r"are established (the manifest's \texttt{licences.undetermined} note).")
    parts.append(r"\ifdefined\pkinvDataTerms\pkinvDataTerms\fi")
    return "\n".join(parts)


def _code_statement(m):
    version = _tex(m["version"])
    doi = _doi(m, "software")
    package = _tex((m.get("product") or {}).get("package", "pkinv"))
    schema = _tex(m.get("schema", ""))
    parts = []
    if doi:
        parts.append(r"The software is release %s of the \texttt{%s} package (manifest schema "
                     r"\texttt{%s}), archived under %s \citep{%s}."
                     % (version, package, schema, _doi_url(doi), BIBKEYS["software"]))
    else:
        parts.append(r"The software is release %s of the \texttt{%s} package (manifest schema "
                     r"\texttt{%s}). The software DOI is assigned on deposit, with the "
                     r"dataset's; until then the release is identified by version and "
                     r"manifest digest." % (version, package, schema))
    parts.append(r"\ifdefined\pkinvCodeTerms\pkinvCodeTerms\fi")
    return "\n".join(parts)


def render(manifest):
    """{relative path: text} for the three generated fragments."""
    m = manifest
    version = _tex(m["version"])
    availability = (HEADER
                    + "\\dataavailability{%s}\n\n" % _data_statement(m)
                    + "\\codeavailability{%s}\n" % _code_statement(m))
    data_doi = _doi(m, "data")
    if data_doi:
        abstract = (r"The dataset is archived under %s \citep{%s}."
                    % (_doi_url(data_doi), BIBKEYS["data"]))
    else:
        abstract = (r"The dataset DOI is assigned on deposit; until then the release is "
                    r"identified by version and manifest digest.")
    abstract_doi = HEADER + abstract + "\n"
    doc_doi = _doi(m, "documentation")
    if doc_doi:
        under = r"%s \citep{%s}" % (_doi_url(doc_doi), BIBKEYS["documentation"])
    else:
        under = "the documentation record, whose identifier is assigned on deposit"
    custody = ("deposited with the data under %s" % under if doc_doi else
               "included in the local release package; external review deposit and persistent identifiers are pending")
    tn = (HEADER
          + "\\newcommand{\\AvailabilityNote}{%\n"
          + "This note is technical documentation of PakEmis %s, %s. "
            "The data-description article and the release manifest "
            "(\\texttt{outputs/release\\_manifest.json}) identify the release this note "
            "documents.}\n" % (version, custody))
    return {AVAILABILITY: availability, ABSTRACT_DOI: abstract_doi, TN_PARAGRAPH: tn}


def load_manifest(root=ROOT):
    with open(asset_path(root, MANIFEST), encoding="utf-8") as handle:
        return json.load(handle)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if a committed fragment differs from a fresh render")
    parser.add_argument("--root", default=ROOT)
    parser.add_argument("--out", default=None)
    args = parser.parse_args(argv)
    out_root = args.out or args.root
    fragments = render(load_manifest(args.root))
    if args.check:
        stale = []
        for rel, text in fragments.items():
            path = asset_path(out_root, rel)
            current = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
            if current != text:
                stale.append(rel)
        if stale:
            print("stale availability fragments (run python3 scripts/make_availability.py): "
                  + ", ".join(stale))
            return 1
        print("availability fragments are current.")
        return 0
    for rel, text in fragments.items():
        path = asset_path(out_root, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(text)
        print("availability fragment written to %s" % rel)
    return 0


if __name__ == "__main__":
    sys.exit(main())

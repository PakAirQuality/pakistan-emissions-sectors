"""Generate the waste factor-provenance appendix (S3) from the data files.

Row-level provenance for every parameter and factor the sector uses: value, unit,
95% uncertainty and an abridged source, rendered straight from data/waste_params.csv
and the waste_burning rows of data/emission_factors.csv. This is where the per-wet
against per-dry tonne bases, the two oxidation factors and the NO-to-NO2 conversion
get row-level treatment instead of caption prose. The compact tab:params in the body
stays; this is its full-provenance form. A test asserts the committed .tex matches a
fresh regeneration and that every engine row appears.

Usage:  python3 scripts/make_waste_factor_table.py
"""

from pkinv.assets import asset_path
import csv
import os
import re
from pkinv.core.io import read_rows

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PARAMS = asset_path(ROOT, "data", "waste_params.csv")
EF = asset_path(ROOT, "data", "emission_factors.csv")
OUT = asset_path(ROOT, "papers", "waste", "sections", "S3_factors.tex")

EF_CATEGORY = "waste_burning"


def _tex(s, width=None):
    s = (s.replace("&", "\\&").replace("%", "\\%").replace("_", "\\_")
         .replace("#", "\\#").replace("$", "\\$"))
    s = re.sub(r"\s+", " ", s).strip()
    if width and len(s) > width:
        s = s[:width - 1].rstrip() + "\\ldots"
    return s


def _fmt(value):
    v = float(value)
    return ("%g" % v)


def param_rows():
    return read_rows(PARAMS, comments=False)


def ef_rows():
    return [r for r in read_rows(EF, comments=False) if r["category"] == EF_CATEGORY]


def render():
    lines = [
        "% GENERATED by scripts/make_waste_factor_table.py - do not hand-edit;",
        "% a test asserts this file matches a fresh regeneration of the data files.",
        "% " + "=" * 75,
        "\\section{Supplementary Table: full factor and parameter provenance}",
        "\\label{app:factors}",
        "% " + "=" * 75,
        "",
        "Every parameter and factor the sector uses, with value, declared 95\\%",
        "uncertainty, PRICED BOUNDS where the source publishes a range, and abridged",
        "source, rendered from the versioned data files the engine reads. Note the",
        "deliberate basis differences the compact table in the",
        "body cannot carry: burning CH$_4$ is per WET tonne and N$_2$O per DRY tonne;",
        "the NO$_x$ factor is converted to NO$_2$-equivalent ($\\times 46/30$) from",
        "Andreae's published NO; and the two oxidation factors describe two different",
        "physical situations and must not be reconciled",
        "(Section~\\ref{sec:factors}). The bounds column exists because a published",
        "range beside a $\\pm$\\% that could not",
        "carry it is a contradiction: such a parameter is now either drawn from those bounds (the effluent N$_2$O factor,",
        "bounded split-triangular in log space) or priced by named endpoint scenarios",
        "(Section~\\ref{app:uncertainty}); a dash means the source states no range.",
        "",
        "\\begin{table*}[htbp]",
        "\\centering",
        "\\tiny",
        "\\begin{tabular}{@{}lrlrlp{0.40\\linewidth}@{}}",
        "\\toprule",
        "\\textbf{Parameter} & \\textbf{Value} & \\textbf{Unit} & "
        "\\textbf{$\\pm$\\%} & \\textbf{Bounds} & \\textbf{Source (abridged)} \\\\",
        "\\midrule",
    ]
    # A parameter the engine draws bounded split-triangular has no honest
    # symmetric width: the ninth review found this table printing the retired
    # "100" beside the effluent factor's own 500-fold range. The +-% cell now
    # names the distribution instead, imported from the engine so no second
    # literal can drift.
    from pkinv.sectors.waste.uncertainty import BOUNDED_DRAW
    for r in param_rows():
        bounds = ("%s--%s" % (_fmt(r["lower"]), _fmt(r["upper"]))
                  if (r.get("lower") or "").strip() else "--")
        if r["param"] in BOUNDED_DRAW:
            width = "bounded split-tri.\\ (log)"
        else:
            width = _fmt(r["uncert_pct"]) if r["uncert_pct"] else "--"
        lines.append("%s & %s & %s & %s & %s & %s \\\\"
                     % (_tex(r["param"]), _fmt(r["value"]), _tex(r["unit"]),
                        width, bounds, _tex(r["source"], 130)))
    lines += [
        "\\midrule",
    ]
    for r in ef_rows():
        lines.append("%s & %s & %s & %s & -- & %s \\\\"
                     % (_tex(r["ef_id"]), _fmt(r["value"]), _tex(r["unit"]),
                        _fmt(r["uncert_pct"]) if r["uncert_pct"] else "--",
                        _tex(r["source"], 130)))
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\caption{Full parameter and factor provenance, generated from",
        "\\texttt{data/waste\\_params.csv} and the \\texttt{waste\\_burning} rows of",
        "\\texttt{data/emission\\_factors.csv}. Each repository row carries the",
        "unabridged source and a note; a provenance test asserts that no row lacks a",
        "citation and that informally sourced values are declared as such.}",
        "\\label{tab:ef-full}",
        "\\end{table*}",
        "",
    ]
    return "\n".join(lines)


def main():
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(render())
    print("wrote %s (%d param + %d factor rows)"
          % (OUT, len(param_rows()), len(ef_rows())))


if __name__ == "__main__":
    main()
